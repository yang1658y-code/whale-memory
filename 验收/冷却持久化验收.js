// ═══════════════════════════════════════════
// ⑩ 阈值外置：改配置天数，判定跟着变（证明代码里没有写死的 30 天）
// ═══════════════════════════════════════════
小标题('⑩ 阈值外置 —— 同记忆天 从 30 改成 7，判定必须跟着变')
{
  const d = 临时目录('阈值')
  const p = path.join(d, '提话冷却.json')
  const 现在 = 基准时
  // 造一条 8 天前提过的记录
  冷却.存冷却(冷却.归一化表({
    已提记录: { 'mem-旧': { 最近: 现在 - 8 * 毫秒每天, 首次: 现在 - 8 * 毫秒每天, 次数: 1 } },
    最近提话: [现在 - 8 * 毫秒每天]
  }, () => {}, 现在), { 路径: p, 现在, 静默: true })

  const 严格 = Object.assign({}, 策略, { 冷却: Object.assign({}, 策略.冷却, { 同记忆天: 30 }) })
  const 宽松 = Object.assign({}, 策略, { 冷却: Object.assign({}, 策略.冷却, { 同记忆天: 7 }) })
  const 读 = 冷却.读冷却({ 路径: p, 静默: true })
  const 上下文 = 冷却.取上下文(读.表, { 现在 })
  const 判严 = 门控策略.门控([造候选('mem-旧')], 严格, 上下文)
  const 判宽 = 门控策略.门控([造候选('mem-旧')], 宽松, 上下文)
  断言('⑩-1', '基线：同记忆天=30 时，8 天前那条仍算冷却中', 判严.开口 === false, 判严.理由)
  断言('⑩-2', '改配置 同记忆天=7 后，同一条可以再提', 判宽.开口 === true, 判宽.理由)
  断言('⑩-3', '门控代码零改动（本轮只换了一个 JSON 字段）', true, '两次判定之间未改任何 .js')

  // 规则来源标注
  const 规则实 = 冷却.取规则(策略)
  const 规则兜 = 冷却.取规则(null)
  断言('⑩-4', '规则来自策略配置（不是代码常量）', 规则实.来源 === '策略配置' && 规则兜.来源 === '内置保守默认',
    `策略=${规则实.同记忆天}天(${规则实.来源})｜兜底=${规则兜.同记忆天}天(${规则兜.来源})`)

  // 源码扫描：不许出现硬编码天数
  const 源 = fs.readFileSync(模块路径, 'utf8')
  const 硬编码 = /同记忆天\s*[:=]\s*\d/.test(源) || /窗口毫秒\s*[:=]\s*\d/.test(源)
  断言('⑩-5', '提话冷却.js 里没有把天数/窗口写死', !硬编码, 硬编码 ? '发现硬编码：同记忆天/窗口毫秒 直接赋了数字' : '扫描通过')
}

