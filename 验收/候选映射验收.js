  断言('极短文本不参与包含匹配', 太短.命中 === false, 太短.原因)

  const 无中 = 映射.找句('量子纠缠与玻色爱因斯坦凝聚的实验装置说明。', 索引, '')
  断言('原文表里没有 → 命中 false 且给原因', 无中.命中 === false && !!无中.原因, 无中.原因)

  const 空 = 映射.找句('', 索引, '')
  断言('空文本 → 命中 false 不崩', 空.命中 === false, 空.原因)

