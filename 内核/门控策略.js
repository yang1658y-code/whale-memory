/**
 * 门控策略.js — L5 主动提话层 · 门控策略引擎（策略层空壳）
 *
 * 一句话：决定「该不该开口」的那一层。策略全在 JSON，代码里没有阈值字面量。
 *
 * ═══════════ 与基线 v7 的接口契约 ═══════════
 *   门控(候选集, 策略, 上下文?) → { 开口, 档位, 置信, 措辞, 理由, 命中, 明细 }
 *
 * 三条强制纪律（代码层面自己守）：
 *   ① 门控函数体内禁止出现任何阈值字面量 —— 0.65 / 3 / 30 全部来自策略对象
 *   ② 「理由」字段必填 —— 不开口时必须逐条说清是哪条 gate 拦的，否则线上无法排障
 *   ③ 配置缺失 / 损坏 / 字段不全 → 回落「内置保守默认」（quiet 档 + 全疑问句），
 *      只记一条 warn，不许崩、不许静默提话
 *
 * 四个切点（基线 v7）：
 *   切点1 门控函数吃一个策略对象，不吃散参数
 *   切点2 档位只是「生效哪些 gate」的子集，不是三套代码
 *   切点3 阈值必须带标定标签，标签不符 → 强制降 quiet + 告警
 *   切点4 冷却表 A案/B案共用（同一条记忆提过就不再提）
 *
 * 故意不做的事：不接检索、不接向量、不接鲸鱼前端、不读会话。
 * 这一层只负责一件事——给一条候选，回答「能不能开口、用什么口气、为什么」。
 *
 * 冷却状态从哪来：本层只认传进来的上下文对象，落盘/自愈/修剪在 内核/提话冷却.js（L0）。
 *   不要在本文件里加 fs 写盘逻辑——分层的意义就是「策略可单测、存储可替换」（断存储演练能过，靠的就是这个）。
 *
 * 会记得你的鲸鱼 · 记忆内核 L5 · 工部制造
 */

const fs = require('fs')
const path = require('path')

// ═══════════════════════════════════════════
// 单位换算常量（注意：这些是「一小时有多少毫秒」，不是策略阈值）
// 真正的阈值（0.65 / k=3 / 30天）一律只活在配置里
// ═══════════════════════════════════════════
const 毫秒每小时 = 60 * 60 * 1000
const 毫秒每天 = 24 * 毫秒每小时

const 默认配置路径 = path.join(__dirname, '..', '配置', '门控策略.json')

// ═══════════════════════════════════════════
// 内置保守默认 —— 断掉配置之后，产品仍是一只懂事的鲸鱼，只是话少
// ═══════════════════════════════════════════
function 内置保守默认() {
  return {
    profile: 'quiet',
    profiles: { quiet: ['cross3'] },
    gates: {
      cross3: { 类型: '交集', 字段: '交集数', k: 3, 置信: '高' }
    },
    标定: null,
    冷却: {
      同记忆天: 30, 每小时上限: 1, 窗口毫秒: 毫秒每小时,
      // 存储纪律（不是策略阈值）：提话冷却.js 修剪落盘表时用，缺了就不修剪
      存储: { 保留倍数: 2, 最近提话上限: 200 }
    },
    措辞: { 高置信: '疑问', 中置信: '疑问' }, // 兜底：全疑问句
    强制疑问句: true,
    // 可提话：疑问句 / 空话 / 自引 —— 保守默认全拦（宁可不提，不许在人设上丢人）
    // 注意与上面「强制疑问句」分开看：那个是说话口吻（用问句的口气提话），
    // 这里判的是**内容是不是一句问话**。名字像，语义两回事。
    可提话: { 排除疑问句: true, 疑问最长字数: 30, 疑问豁免含数字英文: true, 排除空话: true, 排除自引: true },
    来源: '内置保守默认'
  }
}

// ═══════════════════════════════════════════
// 族名归一化：配置里写 literal/rewrite，语料里可能写「字面/改写」
// ═══════════════════════════════════════════
const 族名映射 = {
  literal: 'literal', rewrite: 'rewrite',
  字面: 'literal', 改写: 'rewrite',
  字面族: 'literal', 改写族: 'rewrite'
}
function 归一化族名(v) {
  if (v == null) return null
  const k = String(v).trim()
  return 族名映射[k] || 族名映射[k.toLowerCase()] || k
}

// ═══════════════════════════════════════════
// 配置补全与校验
//   结构性损坏（profiles / gates 不可用）→ 整体回落内置默认
//   非结构性字段缺（冷却 / 措辞 / 标定）  → 用保守值补，记 warn
// ═══════════════════════════════════════════
function 补全校验(原始, 记录) {
  if (!原始 || typeof 原始 !== 'object' || Array.isArray(原始)) {
    记录('warn', '配置内容不是 JSON 对象 → 已回落内置保守默认（quiet + 全疑问句）')
    return { 策略: 内置保守默认(), 修正: ['整体回落'] }
  }
  const 修正 = []
  const 兜底 = 内置保守默认()
  const 策略 = {
    profile: 原始.profile,
    profiles: 原始.profiles,
    gates: 原始.gates,
    标定: 原始.标定 ?? null,
    冷却: Object.assign({}, 兜底.冷却, 原始.冷却 || {}),
    措辞: Object.assign({}, 兜底.措辞, 原始.措辞 || {}),
    强制疑问句: 原始.强制疑问句 === true,
    // 可提话开关（疑问句 / 空话 / 自引）：缺段就用兜底；类型不对也回兜底
    可提话: Object.assign(
      {},
      兜底.可提话,
      (原始.可提话 && typeof 原始.可提话 === 'object' && !Array.isArray(原始.可提话)) ? 原始.可提话 : {}
    ),
    来源: '配置文件'
  }

  // —— profiles 校验
  if (!策略.profiles || typeof 策略.profiles !== 'object' || Array.isArray(策略.profiles) ||
      Object.keys(策略.profiles).length === 0) {
    记录('warn', '配置缺 profiles 或为空 → 已回落内置保守默认（quiet + 全疑问句）')
    return { 策略: Object.assign(内置保守默认(), { 来源: '内置保守默认(profiles损坏)' }), 修正: ['profiles损坏'] }
  }
  // —— gates 校验
  if (!策略.gates || typeof 策略.gates !== 'object' || Array.isArray(策略.gates)) {
    记录('warn', '配置缺 gates → 已回落内置保守默认（quiet + 全疑问句）')
    return { 策略: Object.assign(内置保守默认(), { 来源: '内置保守默认(gates损坏)' }), 修正: ['gates损坏'] }
  }

  // —— 每个 profile 引用的 gate 必须有定义；无定义的 gate 摘掉
  for (const 档 of Object.keys(策略.profiles)) {
    const 名单 = Array.isArray(策略.profiles[档]) ? 策略.profiles[档] : []
    const 有效 = 名单.filter(名 => {
      const g = 策略.gates[名]
      if (!g || typeof g !== 'object') {
        记录('warn', `档位 ${档} 引用了未定义的 gate「${名}」→ 已从该档摘除`)
        修正.push(`摘除未定义gate:${名}`)
        return false
      }
      // 门控判定所需的阈值字段；缺了就等于 gate 永远不通过，必须报出来
      if (g.类型 === '余弦' && !Number.isFinite(Number(g.cosine))) {
        记录('warn', `gate「${名}」缺余弦阈值 cosine → 已从该档摘除`)
        修正.push(`摘除缺阈值gate:${名}`)
        return false
      }
      if (g.类型 === '交集' && !Number.isFinite(Number(g.k))) {
        记录('warn', `gate「${名}」缺交集阈值 k → 已从该档摘除`)
        修正.push(`摘除缺阈值gate:${名}`)
        return false
      }
      return true
    })
    策略.profiles[档] = 有效
  }

  // —— profile 指向的档必须存在，否则挑最保守的一档
  if (!策略.profile || !策略.profiles[策略.profile] || 策略.profiles[策略.profile].length === 0) {
    const 候选档 = [策略.profile, 'quiet', 'standard', Object.keys(策略.profiles)[0]].find(d => d && 策略.profiles[d] && 策略.profiles[d].length > 0)
    记录('warn', `profile「${策略.profile}」不存在或无有效 gate → 已改为「${候选档}」`)
    修正.push(`profile改写:${策略.profile}→${候选档}`)
    策略.profile = 候选档
  }

  // —— 冷却字段缺就用兜底（告警但不改档）
  if (!原始.冷却) { 记录('warn', '配置缺 冷却 段 → 已用兜底冷却（同记忆30天/每小时1次）'); 修正.push('冷却补兜底') }
  if (!原始.措辞) { 记录('warn', '配置缺 措辞 段 → 已用兜底措辞（全疑问句）'); 修正.push('措辞补兜底'); 策略.措辞 = { 高置信: '疑问', 中置信: '疑问' } }
  if (!原始.标定) { 记录('warn', '配置缺 标定 标签 → 阈值无法证明与当前模型同源') }
  if (原始.可提话 !== undefined && (typeof 原始.可提话 !== 'object' || 原始.可提话 === null || Array.isArray(原始.可提话))) {
    记录('warn', '配置的 可提话 段不是对象 → 已用兜底（疑问句/空话/自引全拦）')
    修正.push('可提话补兜底')
  }

  return { 策略, 修正 }
}

// ═══════════════════════════════════════════
// 标定标签自检（切点3）
//   标签与当前 embedding 不一致 → 必降 quiet，禁止静默沿用旧阈值
// ═══════════════════════════════════════════
function 检查标定(策略, 当前模型) {
  const 标定 = 策略 && 策略.标定
  const 当前ID = 当前模型 && (当前模型.模型ID || 当前模型.模型)
  const 当前维 = 当前模型 ? Number(当前模型.维度 ?? 当前模型.dim) : NaN
  if (!当前ID) return { 通过: true, 原因: '调用方未提供当前 embedding 模型信息 → 跳过标定检查（不等于通过）' }
  const 旧标签 = 标定
    ? `模型=${标定.模型} 维度=${标定.维度} 语料=${标定.语料} 样本=${标定.样本} 日期=${标定.日期}`
    : '（无标定段）'
  if (!标定) return { 通过: false, 原因: `旧标签=${旧标签} ≠ 当前=${当前ID}${Number.isFinite(当前维) ? '/' + 当前维 + '维' : ''}`, 旧标签, 当前: `${当前ID}/${当前维}维` }
  const 模型一致 = String(标定.模型) === String(当前ID)
  const 维度一致 = !Number.isFinite(当前维) || Number(标定.维度) === 当前维
  if (!模型一致 || !维度一致) {
    return { 通过: false, 原因: `旧标签=${旧标签} ≠ 当前=${当前ID}/${当前维}维`, 旧标签, 当前: `${当前ID}/${当前维}维` }
  }
  return { 通过: true, 原因: `标定一致（${旧标签}）`, 旧标签 }
}

// ═══════════════════════════════════════════
// 加载策略（唯一入口）
//   选项：{ 路径, 当前模型:{模型ID,维度}, 记录器, 静默 }
//   返回：{ 策略, 日志:[{级别,内容}], 来源, 降档:boolean, 路径 }
// ═══════════════════════════════════════════
function 加载策略(选项 = {}) {
  const 日志 = []
  const 外部记录器 = typeof 选项.记录器 === 'function' ? 选项.记录器 : null
  const 记录 = (级别, 内容) => {
    日志.push({ 级别, 内容 })
    if (外部记录器) { try { 外部记录器(级别, 内容) } catch (e) { /* 记录器自己坏了不许影响门控 */ } }
    if (级别 === 'warn' && 选项.静默 !== true) { try { console.warn('[门控策略] ' + 内容) } catch (e) {} }
  }

  const 配置路径 = 选项.路径 || 默认配置路径
  let 原始 = null
  try {
    原始 = JSON.parse(fs.readFileSync(配置路径, 'utf8'))
  } catch (e) {
    记录('warn', `配置读取失败（${配置路径}）：${e.message} → 已回落内置保守默认（quiet + 全疑问句）`)
    return { 策略: 内置保守默认(), 日志, 来源: '内置默认', 降档: true, 路径: 配置路径, 修正: ['配置不可用'] }
  }

  const { 策略, 修正 } = 补全校验(原始, 记录)

  // —— 标定自检 → 不匹配则强制降 quiet
  let 降档 = false
  const 自检 = 检查标定(策略, 选项.当前模型)
  if (!自检.通过) {
    const 目标档 = (策略.profiles && 策略.profiles.quiet && 策略.profiles.quiet.length) ? 'quiet' : Object.keys(策略.profiles || {})[0]
    if (策略.profile !== 目标档) {
      记录('warn', `标定标签不匹配 → 强制降档 ${策略.profile} → ${目标档}｜${自检.原因}`)
      策略.profile = 目标档
      策略.降档原因 = 自检.原因
      降档 = true
    } else {
      记录('warn', `标定标签不匹配（已在最保守档 ${目标档}，不再降）｜${自检.原因}`)
      策略.降档原因 = 自检.原因
      降档 = true
    }
  } else if (日志.length === 0) {
    记录('info', `策略加载正常：profile=${策略.profile}｜${自检.原因}`)
  }

  return { 策略, 日志, 来源: 策略.来源, 降档, 路径: 配置路径, 修正 }
}

// ═══════════════════════════════════════════
// 单条 gate 判定（所有数字都来自 gate 自身）
// ═══════════════════════════════════════════
function 判定单gate(gate, 候选) {
  if (!gate || typeof gate !== 'object') return { 通过: false, 说明: 'gate 未定义' }
  const 类型 = gate.类型 || (String(gate.名称 || '').indexOf('cosine') === 0 ? '余弦' : '交集')
  const 字段 = gate.字段 || (类型 === '交集' ? '交集数' : '余弦')
  const 实值 = 候选 ? 候选[字段] : undefined

  if (类型 === '交集') {
    const 值 = Number(实值)
    const 门槛 = Number(gate.k)
    if (!Number.isFinite(值)) return { 通过: false, 说明: `${字段}缺失（候选里没有这个字段）` }
    return { 通过: 值 >= 门槛, 说明: `${字段}=${值} ${值 >= 门槛 ? '≥' : '<'} ${门槛}` }
  }

  if (类型 === '余弦') {
    // 族约束：gate 指定族时，候选的族必须匹配（字面族/改写族走不同的路）
    if (gate.族 != null) {
      const 候选族 = 归一化族名(候选 && 候选.族)
      const 门槛族 = 归一化族名(gate.族)
      if (候选族 !== 门槛族) {
        return { 通过: false, 说明: `族不符：候选=${候选族 || '未标'}，本 gate 只收 ${门槛族}` }
      }
    }
    const 值 = Number(实值)
    const 门槛 = Number(gate.cosine)
    if (!Number.isFinite(值)) return { 通过: false, 说明: `${字段}缺失（候选里没有这个字段）` }
    return { 通过: 值 >= 门槛, 说明: `${字段}=${值.toFixed(4)} ${值 >= 门槛 ? '≥' : '<'} ${门槛}` }
  }

  return { 通过: false, 说明: `未知 gate 类型「${类型}」` }
}

// ═══════════════════════════════════════════
// 措辞分级（切点2 的延伸：把准确率问题降级成措辞问题）
//   gate 强制疑问句 / 全局强制疑问句 → 一律疑问
// ═══════════════════════════════════════════
function 选措辞(gate, 策略) {
  if ((gate && gate.强制疑问句 === true) || (策略 && 策略.强制疑问句 === true)) return '疑问'
  const 置信 = (gate && gate.置信) || ((gate && gate.类型 === '余弦') ? '中' : '高')
  const 表 = (策略 && 策略.措辞) || {}
  return 表[置信 + '置信'] || 表.中置信 || '疑问'
}

// ═══════════════════════════════════════════
// 冷却闸（切点4：A案与B案共用一张表）
// ═══════════════════════════════════════════
function 冷却闸(候选, 上下文, 策略) {
  const 冷却 = (策略 && 策略.冷却) || {}
  const 现在 = Number.isFinite(Number(上下文 && 上下文.现在)) ? Number(上下文.现在) : Date.now()
  const id = 候选 && (候选.记忆ID != null ? 候选.记忆ID : 候选.id)

  // ① 同一条记忆：N 天内不再提（A提过的，B也不许提）
  if (id != null && 上下文 && 上下文.已提记录 && 上下文.已提记录[id] != null) {
    const 上次 = Number(上下文.已提记录[id])
    const 天数门槛 = Number(冷却.同记忆天)
    if (Number.isFinite(上次) && Number.isFinite(天数门槛)) {
      const 间隔 = 现在 - 上次
      if (间隔 < 天数门槛 * 毫秒每天) {
        const 小时 = Math.round(间隔 / 毫秒每小时 * 10) / 10
        return { 通过: false, 原因: `冷却中：这条记忆 ${小时} 小时前刚提过，需间隔 ${天数门槛} 天` }
      }
    }
  }

  // ② 频率闸：窗口内提话次数上限
  const 上限 = Number(冷却.每小时上限)
  const 窗口 = Number(冷却.窗口毫秒)
  if (Number.isFinite(上限) && Number.isFinite(窗口) && 上下文 && Array.isArray(上下文.最近提话)) {
    const 近期 = 上下文.最近提话.filter(t => Number.isFinite(Number(t)) && (现在 - Number(t)) < 窗口)
    if (近期.length >= 上限) {
      return { 通过: false, 原因: `频率闸：最近 ${Math.round(窗口 / 毫秒每小时 * 10) / 10} 小时内已提 ${近期.length} 次，上限 ${上限}` }
    }
  }

  return { 通过: true, 原因: '' }
}

// ═══════════════════════════════════════════
// 主函数：门控
//   候选集：按优先级排好序的候选数组（通常是 RRF 融合后的顺序）
//   候选字段约定：{ 记忆ID, 族:'literal'|'rewrite', 交集数, 余弦, ... }
//   上下文（可选）：{ 现在, 已提记录:{记忆ID:时间戳}, 最近提话:[时间戳] }
// ═══════════════════════════════════════════
function 门控(候选集, 策略, 上下文 = {}) {
  const 档位 = (策略 && 策略.profile) || 'none'
  const 结果 = {
    开口: false, 档位, 置信: '低', 措辞: '疑问', 理由: '',
    命中: null, 命中gate: null, 明细: []
  }

  const 名册 = (策略 && 策略.profiles && 策略.profiles[档位]) || []
  if (!名册.length) {
    结果.理由 = `档位「${档位}」没有任何生效 gate → 一律不提（档3一票否决）`
    return 结果
  }

  const 候选数组 = Array.isArray(候选集) ? 候选集.filter(c => c && typeof c === 'object') : []
  if (!候选数组.length) {
    结果.理由 = '候选集为空 → 无话可提'
    return 结果
  }

  const 拦截计数 = {}
  名册.forEach(n => { 拦截计数[n] = 0 })

  for (let i = 0; i < 候选数组.length; i++) {
    const 候选 = 候选数组[i]
    let 命中gate = null
    let 命中gate名 = null
    const 本条明细 = []

    for (const 名 of 名册) {
      const gate = 策略.gates[名]
      const 判定 = 判定单gate(gate, 候选)
      本条明细.push({ 记忆ID: 候选.记忆ID ?? 候选.id, gate: 名, 通过: 判定.通过, 说明: 判定.说明 })
      结果.明细.push({ 记忆ID: 候选.记忆ID ?? 候选.id, gate: 名, 通过: 判定.通过, 说明: 判定.说明 })
      if (判定.通过) { 命中gate = gate; 命中gate名 = 名; break }
    }

    if (!命中gate) {
      名册.forEach(n => {
        const 该门 = 本条明细.find(d => d.gate === n)
        if (该门 && !该门.通过) 拦截计数[n] += 1
      })
      continue
    }

    // —— 过了 gate，还要过冷却闸
    const 冷却 = 冷却闸(候选, 上下文, 策略)
    if (!冷却.通过) {
      结果.明细.push({ 记忆ID: 候选.记忆ID ?? 候选.id, gate: '冷却闸', 通过: false, 说明: 冷却.原因 })
      continue
    }

    // —— 开口
    const 置信 = 命中gate.置信 || (命中gate.类型 === '余弦' ? '中' : '高')
    结果.开口 = true
    结果.置信 = 置信
    结果.措辞 = 选措辞(命中gate, 策略)
    结果.命中 = 候选
    结果.命中gate = 命中gate名
    结果.理由 = `命中 gate「${命中gate名}」（${本条明细.filter(d => d.gate === 命中gate名)[0].说明}），档位=${档位}，置信=${置信}，措辞=${结果.措辞}`
    return 结果
  }

  // —— 全部被拦：理由必须能看出是哪条 gate 拦的
  const 拦截描述 = 名册.map(n => `${n}拦${拦截计数[n]}条`).join('，')
  const 冷却拦 = 结果.明细.filter(d => d.gate === '冷却闸' && !d.通过).length
  const 全为冷却 = 名册.every(n => 拦截计数[n] === 0)
  if (全为冷却 && 冷却拦 > 0) {
    // 不是「不准」，是「刚提过」——这两种不在同一个日志级别上
    const 冷却原因 = 结果.明细.filter(d => d.gate === '冷却闸' && !d.通过).map(d => d.说明)[0] || ''
    结果.理由 = `档位=${档位} 全部候选都过了 gate，但被冷却闸拦下 ${冷却拦} 条（${冷却原因}）→ 不是不准，是刚提过`
  } else {
    结果.理由 = `档位=${档位} 全数未过：${拦截描述}${冷却拦 ? `，冷却闸拦${冷却拦}条` : ''} → 一票否决（未过档1/档2的候选实测准确仅24%，提就是丢人）`
  }
  return 结果
}

// ═══════════════════════════════════════════
// 辅助：开口后登记（A案/B案共用同一张表，调用方存进上下文即可）
// ═══════════════════════════════════════════
function 登记已提(上下文, 候选, 现在 = Date.now()) {
  if (!上下文) return 上下文
  上下文.已提记录 = 上下文.已提记录 || {}
  上下文.最近提话 = 上下文.最近提话 || []
  const id = 候选 && (候选.记忆ID != null ? 候选.记忆ID : 候选.id)
  if (id != null) 上下文.已提记录[id] = 现在
  上下文.最近提话.push(现在)
  return 上下文
}

// ═══════════════════════════════════════════
// 辅助：把门控结果渲染成一句人话（表达层的最小示意，不是产品文案）
// ═══════════════════════════════════════════
function 渲染措辞(结果, 记忆摘要 = '') {
  if (!结果 || !结果.开口) return ''
  const 引 = 记忆摘要 ? `「${记忆摘要}」` : '那件事'
  if (结果.措辞 === '陈述') return `你上次说${引}，我一直记着。`
  return `你之前是不是说过${引}？`
}

