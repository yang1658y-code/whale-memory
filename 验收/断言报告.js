'use strict'
/**
 * 断言报告.js —— 每层验收向「一键跑」报一句机器可读的话
 * ════════════════════════════════════════════════════════════════
 * 【它解决的到底是什么问题】
 *   改之前，一键跑只看子进程退出码：`过 = r.status === 0`。
 *   某个子验收从 66 项悄悄掉到 10 项（改坏了断言、或被注释掉一段），
 *   只要那 10 项都过，退出码仍是 0 —— 一键跑照样绿。
 *   README 上那张 48/48 · 128/128 的表是人工抄的，机器从来不核。
 *
 * 【怎么治】
 *   让每一层在收尾时打印一行统一格式：
 *     ##断言 通过=48 总数=48
 *   一键跑用正则抓这一行，然后三条硬判：
 *     ① 抓不到 → 红（说明这层没报告，断言可能整段没了）
 *     ② 通过 !== 总数 → 红
 *     ③ 总数 < 该层基线总数，或 通过 < 基线通过 → 红（断言只许增不许减）
 *
 * 【为什么单独一个文件】
 *   十层各写一遍同样的话，格式一漂就解析不到了。集中一处，改格式只改这里。
 */

const 前缀 = '##断言'

/** 打印机器可读断言行。参数可以是数字，也可以是对象 {通过, 总数} */
function 报(通过, 总数) {
  const a = Number(通过)
  const b = Number(总数)
  const 行 = 前缀 + ' 通过=' + (Number.isFinite(a) ? a : 0) + ' 总数=' + (Number.isFinite(b) ? b : 0)
  console.log(行)
  return 行
}

/** 解析一段输出里的断言行。返回 {通过, 总数} 或 null */
function 解析(文本) {
  const m = new RegExp(前缀.replace(/[#]/g, '\\#') + '\\s+通过=(\\d+)\\s+总数=(\\d+)').exec(String(文本 || ''))
  if (!m) return null
  return { 通过: Number(m[1]), 总数: Number(m[2]) }
}

module.exports = { 报, 解析, 前缀 }
