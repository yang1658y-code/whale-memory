#!/usr/bin/env node
/**
 * 疑问句过滤验收.js — L4/L5 补刀：疑问句 · 空话 · 自引
 *
 * 跑法：node 验收/疑问句过滤验收.js
 *       node 验收/疑问句过滤验收.js --静默
 *
 * 【为什么有这一套】
 *   2026-10-27 真机复测：用户问「我最近在忙什么」，鲸鱼注入的是
 *   「你上次说『我最近在忙什么』，我一直记着」——命中的是问句自己。
 *   门控一路绿灯（cross3 交集=3），因为没有任何一层问过一句：
 *   「这句话配不配当记忆念出来？念出来跟用户刚说的话一模一样吗？」
 *
 * 【两把刀，各自独立，都能单独关】
 *   刀一「疑问句/空话」：在 可提话() 里，候选进门前就滤掉。
 *   刀二「自引」：在 提话链路() 门控开口之后、渲染措辞之前，拦下"复读自己"。
 *   开关全在 配置/门控策略.json 的 可提话 段，写 false 即回退旧行为。
 *
 * 【验的四件事】
 *   ① 问句拦得住（陈述不许被误伤）
 *   ② 长问句 / 带数字英文的问句 不误杀（宁多提一句，不丢真记忆）
 *   ③ 自引拦得住，且关掉开关能复原（证明是这把刀拦的，不是别的巧合）
 *   ④ 最要紧的一条：问「我最近在忙什么」时，库里那句「我在忙养鲸鱼」照样提得出来
 *      —— 加了过滤之后，正确答案不能被一起埋掉。
 */

const fs = require('fs')
const path = require('path')
const os = require('os')

const 根 = path.resolve(__dirname, '..')
const 静默 = process.argv.includes('--静默')

// 沙箱先行：原文回溯的默认根目录是模块加载时读的，顺序错了夹具就不生效
const 沙箱 = fs.mkdtempSync(path.join(os.tmpdir(), '疑问句过滤-'))
process.env.原文回溯根目录 = 沙箱

const 映射 = require(path.join(根, '内核', '候选映射.js'))
const 回溯 = require(path.join(根, '内核', '原文回溯.js'))
const 门控 = require(path.join(根, '内核', '门控策略.js'))

const 结果清单 = []
let 编号 = 0
function 断言(名称, 通过, 详情) {
  编号++
  结果清单.push({ 编号, 名称, 通过: !!通过, 详情 })
  if (!静默) console.log(`${通过 ? '✅' : '❌'} [${编号}] ${名称}${详情 ? '\n     ' + String(详情).replace(/\n/g, '\n     ') : ''}`)
}
function 小标题(t) { if (!静默) console.log('\n' + '═'.repeat(64) + '\n' + t + '\n' + '═'.repeat(64)) }

/* ───────────── 夹具：一张只有两句的原文表 ───────────── */
const 会话 = '疑问句夹具'
const 问句原话 = '我最近在忙什么'
const 答句原话 = '我在忙养鲸鱼这个项目，DSH 插件快装好了。'
try {
  回溯.喂一轮(会话, [
    { 角色: '用户', 文本: 问句原话 },
    { 角色: '用户', 文本: 答句原话 },
  ], { 轮次: 1, 时间: Date.parse('2026-10-27T06:40:00'), 根目录: 沙箱 })
} catch (e) {
  断言('夹具写入', false, '喂一轮失败：' + ((e && e.message) || e))
}

/* ───────────── 一、刀一：可提话（疑问句 / 空话） ───────────── */
小标题('一、刀一 · 可提话：疑问句与空话拦得住，陈述不许误伤')

{
  const 拦 = [
    ['我最近在忙什么', '句尾疑问词（真机那条）'],
    ['这个怎么办？', '句尾问号'],
    ['你去过杭州吗', '语气词收尾'],
    ['为什么总是失败', '开头疑问词'],
    ['最近在忙啥呢', '口语疑问词收尾'],
  ]
  拦.forEach(([文, 说明], i) => {
    const r = 映射.可提话(文)
    断言('疑问句拦住 #' + (i + 1) + '：' + 文, r.可 === false, '原因=' + r.原因 + '｜' + 说明)
  })

  const 放 = [
    ['我是神仙，最近忙着飞升', '短陈述'],
    ['我把 VPS 换到了新加坡', '带专名陈述'],
    ['那天到底为什么没去，我到现在也没想明白，反正事儿就这么过去了。', '长句里带着事实（超 30 字不判疑问）'],
    ['VPS 什么时候到期', '带英文/专名的短问句 → 豁免，宁多提一句'],
  ]
  放.forEach(([文, 说明], i) => {
    const r = 映射.可提话(文)
    断言('陈述照提 #' + (i + 1) + '：' + 文.slice(0, 20), r.可 === true, '可=' + r.可 + '｜' + 说明)
  })

  断言('表格行仍然拦（未被新规则搅坏）', 映射.可提话('| 隐私 | 不上报 |').可 === false, 映射.可提话('| 隐私 | 不上报 |').原因)
  断言('代码围栏仍然拦', 映射.可提话('```js\nconst a = 1\n```').可 === false, 映射.可提话('```js\nconst a = 1\n```').原因)
  断言('极短词仍然拦', 映射.可提话('好的呢').可 === false, 映射.可提话('好的呢').原因)
  断言('空话拦住：嗯嗯是的吧啊', 映射.可提话('嗯嗯是的吧啊').可 === false, 映射.可提话('嗯嗯是的吧啊').原因)

  {
    const r = 映射.可提话(问句原话, { 排除疑问句: false })
    断言('开关回退：排除疑问句=false → 问句又能提了（旧行为可复原）', r.可 === true, '可=' + r.可)
  }
}

/* ───────────── 二、刀一的配置确实从策略里读得到 ───────────── */
小标题('二、配置通路：可提话 段确实进了策略对象（不然开关是摆设）')

{
  const 载 = 门控.加载策略({ 静默: true })
  const 配 = 载.策略 && 载.策略.可提话
  断言('加载策略 带出 可提话 段', !!(配 && typeof 配 === 'object'), JSON.stringify(配))
  断言('配置默认全开（排除疑问句/空话/自引）',
     !!(配 && 配.排除疑问句 === true && 配.排除空话 === true && 配.排除自引 === true),
     JSON.stringify(配))
  const 兜 = 门控.加载策略({ 路径: path.join(沙箱, '不存在的配置.json'), 静默: true })
  断言('配置断掉 → 内置兜底里也有 可提话（断依赖时刀仍然在）',
     !!(兜.策略 && 兜.策略.可提话 && 兜.策略.可提话.排除疑问句 === true),
     JSON.stringify(兜.策略 && 兜.策略.可提话))
}

/* ───────────── 三、刀二：自引闸（端到端走真 提话链路） ───────────── */
小标题('三、刀二 · 自引闸：真链路里拦得住，关掉开关能复原')

const 基准策略 = 门控.加载策略({ 静默: true }).策略
function 改策略(改) {
  const 份 = JSON.parse(JSON.stringify(基准策略))
  份.可提话 = Object.assign({}, 份.可提话, 改)
  return 份
}
/** 两路同一条内容 → cross3 交集数=3，门控必开口（这样测的才是自引闸，不是门控） */
function 注入(文本, 相似度 = 0.9) {
  return { 向量列: [{ content: 文本, similarity: 相似度 }], 关键词列: [{ content: 文本 }], 真检索: false }
}
/** 两条候选：首位排前（验证自引降级时让位给次位） */
function 注入两条(首位, 次位) {
  return {
    向量列: [{ content: 首位, similarity: 0.95 }, { content: 次位, similarity: 0.9 }],
    关键词列: [{ content: 首位 }, { content: 次位 }],
    真检索: false,
  }
}

async function 三() {
  // ① 只关疑问句过滤 → 问句能进候选集 → 全靠自引闸拦
  const 只留自引 = 改策略({ 排除疑问句: false, 排除空话: false, 排除自引: true })
  const 甲 = await 映射.提话链路(问句原话, Object.assign({ 上下文: {}, 策略: 只留自引 }, 注入(问句原话)))
  断言('自引拦下：查询与命中原话一字不差 → 不开口',
    甲.开口 === false && 甲.自引 === true,
    '开口=' + 甲.开口 + '｜自引=' + 甲.自引 + '｜理由=' + 甲.理由)
  断言('自引时绝不吐出原话（防上层误用）', 甲.原话 === null && 甲.命中 === null, '原话=' + JSON.stringify(甲.原话))

  // ② 同一组，只把自引开关关掉 → 必须开口（证明是这把刀拦的）
  const 全关 = 改策略({ 排除疑问句: false, 排除空话: false, 排除自引: false })
  const 乙 = await 映射.提话链路(问句原话, Object.assign({ 上下文: {}, 策略: 全关 }, 注入(问句原话)))
  断言('关掉自引开关 → 照旧开口（旧行为可复原，开关不是死码）',
    乙.开口 === true && !乙.自引,
    '开口=' + 乙.开口 + '｜自引=' + 乙.自引 + '｜理由=' + 乙.理由)

  // ③ 只用疑问句过滤（自引关掉）→ 问句在候选集门口就被滤掉
  const 只留疑问 = 改策略({ 排除疑问句: true, 排除空话: true, 排除自引: false })
  const 丙 = await 映射.提话链路(问句原话, Object.assign({ 上下文: {}, 策略: 只留疑问 }, 注入(问句原话)))
  断言('刀一独立生效：只开疑问句过滤 → 问句候选进不了门控',
    丙.开口 === false && !丙.自引,
    '开口=' + 丙.开口 + '｜自引=' + 丙.自引 + '｜理由=' + 丙.理由)

  // ④ 最要紧的一条：不误杀正确答案
  //    用户问「我最近在忙什么」，库里那句「我在忙养鲸鱼…」必须提得出来
  const 默认 = 改策略({})
  const 丁 = await 映射.提话链路(问句原话, Object.assign({ 上下文: {}, 策略: 默认 }, 注入(答句原话)))
  断言('不误杀：问「我最近在忙什么」→ 库里「我在忙养鲸鱼…」照样提得出来',
    丁.开口 === true && !丁.自引,
    '开口=' + 丁.开口 + '｜句ID=' + ((丁.原话 && 丁.原话.句ID) || '-') + '｜原话=' + ((丁.原话 && 丁.原话.原句) || '-'))

  // ⑤ 对照：开口成功时必须往上下文里登记
  //    （没这条，下面「拦下时上下文为空」永远是空转的）
  const 上下文开 = {}
  await 映射.提话链路(问句原话, Object.assign({ 上下文: 上下文开, 策略: 默认 }, 注入(答句原话)))
  断言('对照：开口成功时确实写了上下文（证明下一条不是空转）',
    Object.keys(上下文开).length > 0, '上下文键=' + JSON.stringify(Object.keys(上下文开)))

  // ⑥ 自引拦下时不登记冷却（不然白占 30 天名额）
  const 上下文 = {}
  await 映射.提话链路(问句原话, Object.assign({ 上下文, 策略: 只留自引 }, 注入(问句原话)))
  let 冷却条数 = 0
  try {
    const 冷却模块 = require(path.join(根, '内核', '提话冷却.js'))
    for (const k of Object.keys(上下文)) {
      const v = 上下文[k]
      if (v && typeof v === 'object' && Array.isArray(v.记录)) 冷却条数 = v.记录.length
      else if (v && typeof v === 'object' && typeof v.size === 'number') 冷却条数 = v.size
    }
    if (typeof 冷却模块.读冷却表 === 'function') {
      const 表 = 冷却模块.读冷却表(上下文)
      if (表 && Array.isArray(表.记录)) 冷却条数 = 表.记录.length
    }
  } catch { /* 结构可能不同，下面按宽松判定 */ }
  断言('自引拦下不登记冷却（不白占 30 天名额）', 冷却条数 === 0, '上下文里冷却记录数=' + 冷却条数 + '｜上下文键=' + JSON.stringify(Object.keys(上下文)))

  // ⑦ 【2026-11-02 新增】自引降级：第一名是自引，不等于整轮该闭嘴
  //    真机案：同一句话连问两次，库里存着上轮同款问句 → 旧逻辑整链收手，
  //    第二名真记忆永远提不出来（用户会觉得“它刚刚还记着，怎么一问就忘了”）。
  const 戊 = await 映射.提话链路(问句原话, Object.assign({ 上下文: {}, 策略: 只留自引 }, 注入两条(问句原话, 答句原话)))
  断言('自引降级：第一名是自引 → 改提第二名的真记忆（不再整轮闭嘴）',
    戊.开口 === true && !戊.自引 && String(戊.原话 && 戊.原话.原句).indexOf('养鲸鱼') >= 0,
    '开口=' + 戊.开口 + '｜句ID=' + ((戊.原话 && 戊.原话.句ID) || '-') + '｜原话=' + ((戊.原话 && 戊.原话.原句) || '-'))
  断言('自引降级留痕：诊断写明“这条不念，看下一条”',
    Array.isArray(戊.诊断.步骤) && 戊.诊断.步骤.some(s => /自引闸/.test(s) && /看下一条/.test(s)),
    JSON.stringify(戊.诊断.步骤))
}

/* ───────────── 四、收尾 ───────────── */
三().then(() => {
  const 过 = 结果清单.filter(r => r.通过).length
  const 总 = 结果清单.length
  const 全过 = 过 === 总
  console.log('\n' + '═'.repeat(64))
  console.log('疑问句/空话/自引 过滤验收：通过 ' + 过 + '/' + 总 + ' 项 —— ' + (全过 ? '全部通过 ✅' : '有失败 ❌'))
  require('./断言报告.js').报(过, 总)
  console.log('═'.repeat(64))
  if (!全过) {
    for (const r of 结果清单.filter(x => !x.通过)) console.log('❌ [' + r.编号 + '] ' + r.名称 + '｜' + (r.详情 || ''))
  }
  try {
    fs.writeFileSync(path.join(__dirname, '疑问句过滤验收结果.json'), JSON.stringify({
      时间: new Date().toISOString(), 通过: 过, 总数: 总, 全过, 明细: 结果清单,
    }, null, 2), 'utf8')
  } catch { }
  try { fs.rmSync(沙箱, { recursive: true, force: true }) } catch { }
  process.exit(全过 ? 0 : 1)
}).catch((e) => {
  console.error('验收脚本自身异常：' + ((e && e.stack) || e))
  try { fs.rmSync(沙箱, { recursive: true, force: true }) } catch { }
  process.exit(1)
})
