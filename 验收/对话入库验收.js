function 九组_回归() {
  小标题('九、回归（改了向量记忆.js / 候选映射.js，既有验收必须仍全过）')

  const 套 = [
    ['候选映射验收（L4）', path.join(__dirname, '候选映射验收.js'), /108/],
    ['门控策略验收（L5）', path.join(__dirname, '门控策略验收.js'), /20/],
    ['冷却持久化验收（L0）', path.join(__dirname, '冷却持久化验收.js'), /48/],
    ['原文回溯验收（L1）', path.join(__dirname, '原文回溯验收.js'), /通过 \d+ 项 \/ 失败 0 项/]
  ]
  for (const [名, 脚本, 特征] of 套) {
    let 出
    try {
      出 = cp.spawnSync(process.execPath, [脚本, '--静默'], { encoding: 'utf8', timeout: 240000, windowsHide: true })
    } catch (e) {
      断言(名 + ' 可执行', false, e && e.message)
      continue
    }
    const 文 = String(出.stdout || '') + String(出.stderr || '')
    断言(名 + ' 退出码 0', 出.status === 0, 'status=' + 出.status + '｜' + 文.slice(-300))
    断言(名 + ' 输出含特征数字', 特征.test(文), 文.slice(-180).replace(/\n/g, ' '))
  }
}

