  console.log('═'.repeat(64))

  try {
    fs.writeFileSync(path.join(__dirname, '对话入库验收结果.json'), JSON.stringify({
      时间: new Date().toISOString(), 通过: 过, 总数: 总, 耗时毫秒: Date.now() - 开始, 结果: 结果清单
    }, null, 1), 'utf8')
  } catch { }

  process.exit(败.length ? 1 : 0)
