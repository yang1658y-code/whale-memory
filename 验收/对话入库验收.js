  断言('真跑：向量真写进 2 条（三级降级必有兜底）', r.向量.写入 === 2, JSON.stringify(r.向量.明细))

  // 【修】读取不传根目录 → 读的是默认库（临时数据），而上面写入走的是 临时根，两处不同库，
  // 断言必然报「条目数=0”，后续 本条[0] 还会 TypeError。根源在这里，不在入库层。
  const 库 = 向量模块.读取向量库({ 根目录: 临时根 }) || []
