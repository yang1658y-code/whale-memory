  const 适 = 映射.可提话(
    '先给这个事挂份需求单出来吧。')
  断言('可提话：正常句子 → 可', 适.可 === true, JSON.stringify(适))
  断言('可提话：表格行 → 不可', 映射.可提话('[文档/x.md:109] | 隐私 | 不上报、不追踪 |').可 === false,
    映射.可提话('[文档/x.md:109] | 隐私 | 不上报、不追踪 |').原因)
  断言('可提话：标题行 → 不可', 映射.可提话('### 一、需求单头').可 === false, 映射.可提话('### 一、需求单头').原因)
  断言('可提话：代码围栏 → 不可', 映射.可提话('```js\nconst a=1\n```').可 === false, 映射.可提话('```js\nconst a=1\n```').原因)
  断言('可提话：分隔线 → 不可', 映射.可提话('═══════════').可 === false, 映射.可提话('═══════════').原因)
  断言('可提话：纯链接 → 不可', 映射.可提话('https://example.com/x').可 === false, 映射.可提话('https://example.com/x').原因)
  断言('可提话：极短词 → 不可', 映射.可提话('好').可 === false, 映射.可提话('好').原因)
  断言('可提话：空前缀后为空 → 不可', 映射.可提话('[a.md:1]').可 === false, 映射.可提话('[a.md:1]').原因)
