/**
 * 合成一张与上游对话记录同形的原文表：31 轮 / 88 句 / 0 坏行。
 *   · 第 15 轮第 1 句 = 要回溯的那句
 *   · 第 14 轮末句 / 第 16 轮首句 留着做跨轮邻居
 *   · 第 13 轮第 2 句 = 多句用例的前半段
 * 只在夹具目录为空时生成，重复跑不重建（句ID 恒定）。
 */
function 准备夹具() {
  const 会话 = '对话-2026-10-26'
  const 表路径 = path.join(夹具根, '原文表-' + 会话 + '.jsonl')
  try {
    if (fs.existsSync(表路径) && fs.statSync(表路径).size > 0) return { 已存在: true, 表路径 }
  } catch { }
  fs.mkdirSync(夹具根, { recursive: true })
  const 句数表 = {}
  for (let 轮 = 1; 轮 <= 31; 轮++) 句数表[轮] = 3
  句数表[14] = 2
  句数表[15] = 1
  句数表[16] = 1
  const 起点 = Date.parse('2026-10-26T03:05:00')
  let 总句 = 0
  for (let 轮 = 1; 轮 <= 31; 轮++) {
    const 条数 = 句数表[轮]
    const 消息们 = []
    for (let j = 1; j <= 条数; j++) {
      let 文本
      if (轮 === 15 && j === 1) 文本 = '先给这个事挂份需求单出来吧。'
      else if (轮 === 13 && j === 2) 文本 = '我说的是在DSH养鲸鱼这个赛道上，不是真正的要去主战场拼。'
      else if (轮 === 14 && j === 2) 文本 = '需求单头先立起来，版本号慢慢升。'
      else if (轮 === 16 && j === 1) 文本 = '需求单已经挂出，此后每轮按它办。'
      else 文本 = '第' + 轮 + '轮第' + j + '句：日常事务记录，无须逐字保留。'
      消息们.push({ 角色: '用户', 文本 })
    }
    回溯.喂一轮(会话, 消息们, { 轮次: 轮, 时间: 起点 + (轮 - 1) * 60000, 根目录: 夹具根 })
    总句 += 条数
  }
  return { 已存在: false, 表路径, 总句 }
}

