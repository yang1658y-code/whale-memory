/**
 * 提话冷却.js — L0 存储层 · 冷却表持久化（基线 v9 动工第一刀）
 *
 * 一句话：鲸鱼重启之后，必须还记得自己昨天说过什么。
 *
 * ═══════════ 为什么要有这一层 ═══════════
 * 门控策略.js（L5）只认一个「上下文对象」，冷却状态由调用方传进来——纸面上对，
 * 但鲸鱼一重启，内存里的上下文清零 → 昨天提过的事今天重提一遍。
 * 用户体感上，"重复提起同一件事"比"偶尔提错一件事"更伤人设：提错可以纠正，
 * 重复说明它压根没在听。所以这一层管的是「提完不忘」，不是「提得准」。
 *
 * ═══════════ 职责边界（契约隔离） ═══════════
 *   存什么：哪条记忆提过、什么时候提的、提了几次、用什么措辞、是A案还是B案
 *   不存什么：记忆正文、向量、会话（那是 L1/L2 的事）
 *   不给谁用：不 require 向量记忆/会话/前端；只 require fs + 门控策略.js（取兜底规则）
 *
 * ═══════════ 四个切点 ═══════════
 *   切点1 门控策略.js 一行不改也能跑 —— 本模块只负责喂它 {已提记录, 最近提话}
 *   切点2 阈值全在外：同记忆天/窗口/上限/修剪参数全部来自 策略.冷却，
 *         代码内不出现任何业务阈值字面量（只有 0/1 这类结构性常量）
 *   切点3 坏文件不静默丢：坏内容另存 `.坏-<时间戳>` 留证据，再从 .bak 恢复
 *   切点4 A案/B案共用同一张表：登记时记「来源案」，但冷却判定不区分案别
 *
 * ═══════════ 落盘纪律 ═══════════
 *   ① 原子写：写 .tmp-<pid> → rename 覆盖，绝不出现半截 JSON
 *   ② 每次写前把「能解析的旧主文件」备份成 .bak（坏文件不许覆盖好备份）
 *   ③ 主文件丢了/坏了 → 从 .bak 自愈恢复并回写主文件（自愈默认开，可关）
 *   ④ 表结构升级带 版本 字段，读老格式（数字时间戳）自动归一成对象
 *
 * 对外接口：
 *   读冷却(选项)              → { 表, 来源, 日志, 路径 }
 *   取上下文(表, 选项)        → { 现在, 已提记录:{id:ts}, 最近提话:[ts] }  ← 直接喂 门控()
 *   登记提话(候选|ID, 选项)   → 读-改-写一趟落盘，返回 { ok, 表, 路径 }
 *   开口并登记(候选集, 策略) → 读表→门控→开口则落盘，返回 { 结果, 表, 登记 }
 *   清表(选项)                → 归档旧表后重建空表（运维/测试用）
 *   自述()
 *
 * 会记得你的鲸鱼 · 记忆内核 L0 · 工部制造
 */

const fs = require('fs')
const path = require('path')
const 门控策略 = require('./门控策略.js')

const 根 = path.resolve(__dirname, '..')
const 默认路径 = path.join(根, '数据', '提话冷却.json')
const 表版本 = 2 // v1=裸时间戳 | v2={最近,首次,次数,措辞,档位,来源案}
const 毫秒每天 = 门控策略.毫秒每天

// ═══════════════════════════════════════════
// 规则：业务参数只从 策略.冷却 拿；不传策略就用门控层的内置保守默认
// ═══════════════════════════════════════════
function 取规则(策略) {
  const 兜底 = 门控策略.内置保守默认().冷却 || {}
  const 配置 = (策略 && 策略.冷却) || {}
  const 数 = (v, d) => (Number.isFinite(Number(v)) ? Number(v) : d)
  return {
    同记忆天: 数(配置.同记忆天, 兜底.同记忆天),
    每小时上限: 数(配置.每小时上限, 兜底.每小时上限),
    窗口毫秒: 数(配置.窗口毫秒, 兜底.窗口毫秒),
    存储: Object.assign({}, 兜底.存储 || {}, 配置.存储 || {}),
    来源: 策略 && 策略.冷却 ? '策略配置' : '内置保守默认'
  }
}

function 现在时刻(选项) {
  return Number.isFinite(Number(选项 && 选项.现在)) ? Number(选项.现在) : Date.now()
}

function 归一ID(候选或ID) {
  const v = (候选或ID && typeof 候选或ID === 'object')
    ? (候选或ID.记忆ID != null ? 候选或ID.记忆ID : 候选或ID.id)
    : 候选或ID
  return v == null ? null : String(v)
}

// ═══════════════════════════════════════════
// 表结构归一：老格式（数字）→ 新格式（对象），坏值丢弃并记 warn
// ═══════════════════════════════════════════
function 空表(现在 = Date.now()) {
  return { 版本: 表版本, 创建: 现在, 更新: 现在, 已提记录: {}, 最近提话: [] }
}

function 归一化表(原始, 记录 = () => {}, 现在 = Date.now()) {
  if (!原始 || typeof 原始 !== 'object' || Array.isArray(原始)) {
    if (原始 != null) 记录('warn', '冷却表内容不是 JSON 对象 → 按空表处理')
    return 空表(现在)
  }
  const 表 = 空表(现在)
  表.创建 = Number.isFinite(Number(原始.创建)) ? Number(原始.创建) : 现在
  表.更新 = Number.isFinite(Number(原始.更新)) ? Number(原始.更新) : 现在
  表.版本 = 表版本

  const 原记录 = 原始.已提记录
  if (原记录 && typeof 原记录 === 'object' && !Array.isArray(原记录)) {
    for (const [id, v] of Object.entries(原记录)) {
      if (typeof v === 'number' || typeof v === 'string') {
        // v1 老格式：裸时间戳
        const ts = Number(v)
        if (Number.isFinite(ts)) 表.已提记录[id] = { 最近: ts, 首次: ts, 次数: 1, 措辞: null, 档位: null, 来源案: null }
        continue
      }
      if (v && typeof v === 'object') {
        const 最近 = Number(v.最近 != null ? v.最近 : v.上次)
        if (!Number.isFinite(最近)) { 记录('warn', `冷却记录 ${id} 缺有效时间戳 → 已丢弃`); continue }
        表.已提记录[id] = {
          最近,
          首次: Number.isFinite(Number(v.首次)) ? Number(v.首次) : 最近,
          次数: Number.isFinite(Number(v.次数)) ? Number(v.次数) : 1,
          措辞: v.措辞 || null,
          档位: v.档位 || null,
          来源案: v.来源案 || null
        }
      }
    }
  } else if (原记录 != null) {
    记录('warn', '冷却表 已提记录 字段不是对象 → 按空处理（原文不受影响）')
  }

  if (Array.isArray(原始.最近提话)) {
    表.最近提话 = 原始.最近提话.map(Number).filter(Number.isFinite)
  } else if (原始.最近提话 != null) {
    记录('warn', '冷却表 最近提话 字段不是数组 → 按空处理')
  }
  return 表
}

// ═══════════════════════════════════════════
// 修剪：过期记录清掉，窗口流水带上限（参数全在 规则.存储）
// ═══════════════════════════════════════════
function 修剪表(表, 规则, 现在) {
  const 保留倍数 = Number(规则.存储 && 规则.存储.保留倍数)
  const 流水上限 = Number(规则.存储 && 规则.存储.最近提话上限)
  let 清掉 = 0
  if (Number.isFinite(保留倍数) && Number.isFinite(规则.同记忆天)) {
    const 寿命 = 规则.同记忆天 * 毫秒每天 * 保留倍数
    for (const id of Object.keys(表.已提记录)) {
      const ts = Number(表.已提记录[id] && 表.已提记录[id].最近)
      if (!Number.isFinite(ts) || (现在 - ts) > 寿命) { delete 表.已提记录[id]; 清掉++ }
    }
  }
  if (Number.isFinite(流水上限) && 流水上限 > 0 && 表.最近提话.length > 流水上限) {
    // 先按时间升序再截尾：手工编辑/老格式/异常写入搞乱顺序时，也不会把最近的那批截掉
    表.最近提话 = 表.最近提话.slice().sort((a, b) => a - b).slice(-流水上限)
  }
  return 清掉
}

// ═══════════════════════════════════════════
// 坏文件留证据：另存 .坏-<时间戳>，绝不覆盖、绝不删
// ═══════════════════════════════════════════
function 留证据(主路径, 现在) {
  const 目标 = `${主路径}.坏-${现在}`
  try { fs.copyFileSync(主路径, 目标); return 目标 } catch (e) { return null }
}

// ═══════════════════════════════════════════
// 读：主文件 → 坏则从 .bak 自愈 → 都没有则空表
//   绝不抛错，绝不崩，只 warn
// ═══════════════════════════════════════════
function 读冷却(选项 = {}) {
  const 日志 = []
  const 记录 = (级别, 内容) => {
    日志.push({ 级别, 内容 })
    if (选项.静默 !== true) { try { console.warn('[提话冷却] ' + 内容) } catch (e) {} }
  }
  const 路径 = 选项.路径 || 默认路径
  const 备路径 = 路径 + '.bak'
  const 现在 = 现在时刻(选项)

  let 原始 = null
  let 来源 = '磁盘'
  let 证据 = null

  if (fs.existsSync(路径)) {
    try {
      原始 = JSON.parse(fs.readFileSync(路径, 'utf8'))
    } catch (e) {
      记录('warn', `冷却表主文件损坏（${e.message}）→ 另存证据后尝试从备份恢复`)
      证据 = 留证据(路径, 现在)
    }
  } else {
    来源 = '新建空表'
  }

  if (原始 == null && fs.existsSync(备路径)) {
    try {
      原始 = JSON.parse(fs.readFileSync(备路径, 'utf8'))
      来源 = '从备份恢复'
      记录('warn', '冷却表主文件不可用 → 已从 .bak 恢复（提过的记忆不会重复提）')
    } catch (e) {
      记录('warn', `冷却表备份也损坏（${e.message}）→ 按空表启动，历史提话记录丢失（原文不受影响）`)
      来源 = '坏文件重建空表'
    }
  } else if (原始 == null && 来源 !== '新建空表') {
    来源 = '坏文件重建空表'
    记录('warn', '冷却表主文件与备份都不可用 → 按空表启动（只影响「不重复提话」，不影响记忆本身）')
  }

  const 表 = 归一化表(原始, 记录, 现在)

  // 自愈：从备份恢复 或 坏文件重建后，立刻把干净的表写回主文件
  if (选项.自愈 !== false && (来源 === '从备份恢复' || 来源 === '坏文件重建空表')) {
    try {
      存冷却(表, { 路径, 现在, 静默: true })
      记录('info', `冷却表已自愈回写：${路径}`)
    } catch (e) {
      记录('warn', `冷却表自愈回写失败（${e.message}）→ 仅内存可用，不影响本次提话判定`)
    }
  }

  return { 表, 来源, 日志, 路径, 证据 }
}

// ═══════════════════════════════════════════
// 写：原子写（tmp → rename），写前只在旧文件可解析时覆盖 .bak
// ═══════════════════════════════════════════
function 存冷却(表, 选项 = {}) {
  const 路径 = 选项.路径 || 默认路径
  const 备路径 = 路径 + '.bak'
  const 现在 = 现在时刻(选项)
  const 净 = 归一化表(表, () => {}, 现在)
  净.版本 = 表版本
  净.更新 = 现在
  const 文本 = JSON.stringify(净, null, 2)

  fs.mkdirSync(path.dirname(路径), { recursive: true })

  // 备份：只有旧主文件能解析才覆盖 .bak（坏文件不许把好备份挤掉）
  if (fs.existsSync(路径)) {
    let 旧可解析 = false
    try { JSON.parse(fs.readFileSync(路径, 'utf8')); 旧可解析 = true } catch (e) { 旧可解析 = false }
    if (旧可解析) { try { fs.copyFileSync(路径, 备路径) } catch (e) {} }
  }

  const 临时 = `${路径}.tmp-${process.pid}`
  fs.writeFileSync(临时, 文本, 'utf8')
  try {
    fs.renameSync(临时, 路径)
  } catch (e) {
    // Windows 上偶发文件占用 → 退回直接写（仍保证内容完整，只是非原子）
    try { fs.writeFileSync(路径, 文本, 'utf8') } finally { try { fs.unlinkSync(临时) } catch (_) {} }
    if (选项.静默 !== true) { try { console.warn('[提话冷却] 原子写回落直接写：' + e.message) } catch (_) {} }
  }
  return { ok: true, 路径, 备份: 备路径, 条数: Object.keys(净.已提记录).length, 表: 净 }
}

// ═══════════════════════════════════════════
// 上下文：把落盘表压成门控策略.js 认的扁平形状
//   已提记录[id] 必须是数字时间戳（对象会让 门控 的 Number() 得到 NaN → 冷却失效）
// ═══════════════════════════════════════════
function 取上下文(表, 选项 = {}) {
  const 现在 = 现在时刻(选项)
  const 已提记录 = {}
  for (const [id, v] of Object.entries((表 && 表.已提记录) || {})) {
    const ts = (v && typeof v === 'object') ? Number(v.最近) : Number(v)
    if (Number.isFinite(ts)) 已提记录[id] = ts
  }
  const 最近提话 = Array.isArray(表 && 表.最近提话) ? 表.最近提话.map(Number).filter(Number.isFinite) : []
  return { 现在, 已提记录, 最近提话 }
}

// ═══════════════════════════════════════════
// 登记：读-改-写一趟（同步，进程内天然串行；跨进程靠原子写保证不出半截）
// ═══════════════════════════════════════════
function 登记提话(候选或ID, 选项 = {}) {
  const 路径 = 选项.路径 || 默认路径
  const 现在 = 现在时刻(选项)
  const id = 归一ID(候选或ID)
  const 日志 = []
  const 记录 = (级别, 内容) => {
    日志.push({ 级别, 内容 })
    if (选项.静默 !== true) { try { console.warn('[提话冷却] ' + 内容) } catch (e) {} }
  }
  if (id == null) {
    记录('warn', '登记提话被跳过：候选没有 记忆ID/id')
    return { ok: false, 原因: '缺记忆ID', 表: null, 路径 }
  }

  const 读 = 读冷却({ 路径, 现在, 静默: true })
  const 表 = 读.表
  const 旧 = 表.已提记录[id]
  表.已提记录[id] = {
    最近: 现在,
    首次: (旧 && Number.isFinite(Number(旧.首次))) ? Number(旧.首次) : 现在,
    次数: ((旧 && Number.isFinite(Number(旧.次数))) ? Number(旧.次数) : 0) + 1,
    措辞: 选项.措辞 || (旧 && 旧.措辞) || null,
    档位: 选项.档位 || (旧 && 旧.档位) || null,
    来源案: 选项.来源案 || (旧 && 旧.来源案) || null
  }
  表.最近提话.push(现在)

  const 规则 = 取规则(选项.策略)
  修剪表(表, 规则, 现在)
  const 写 = 存冷却(表, { 路径, 现在, 静默: true })
  return { ok: true, 表: 写.表, 路径, 备份: 写.备份, 日志: 日志.concat(读.日志), 读来源: 读.来源, 证据: 读.证据 }
}

// ═══════════════════════════════════════════
// 开口并登记：L0 + L5 的粘合口，A案/B案都走这一个函数（切点4）
//   选项：{ 路径, 现在, 策略, 来源案:'A'|'B' }
// ═══════════════════════════════════════════
function 开口并登记(候选集, 策略, 选项 = {}) {
  const 路径 = 选项.路径 || 默认路径
  const 现在 = 现在时刻(选项)
  const 读 = 读冷却({ 路径, 现在, 静默: true })
  const 上下文 = 取上下文(读.表, { 现在 })
  const 结果 = 门控策略.门控(候选集, 策略, 上下文)
  let 登记 = null
  if (结果.开口) {
    登记 = 登记提话(结果.命中, {
      路径, 现在, 静默: true, 策略,
      措辞: 结果.措辞, 档位: 结果.档位, 来源案: 选项.来源案 || null
    })
  }
  return { 结果, 表: (登记 && 登记.表) || 读.表, 登记, 读来源: 读.来源, 日志: 读.日志 }
}

// ═══════════════════════════════════════════
// 清表：归档旧表（.旧-<时间戳>）后重建空表。运维/测试用，产品里不调用
// ═══════════════════════════════════════════
function 清表(选项 = {}) {
  const 路径 = 选项.路径 || 默认路径
  const 现在 = 现在时刻(选项)
  const 归档 = fs.existsSync(路径) ? (function () {
    const 目标 = `${路径}.旧-${现在}`
    try { fs.copyFileSync(路径, 目标); return 目标 } catch (e) { return null }
  })() : null
  const 写 = 存冷却(空表(现在), { 路径, 现在, 静默: 选项.静默 })
  return { ok: true, 路径, 归档, 表: 写.表 }
}

