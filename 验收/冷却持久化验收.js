// ═══════════════════════════════════════════
// ③ 重启不忘 —— 子进程读同一份表（本刀的核心）
// ═══════════════════════════════════════════
小标题('③ 重启不忘 —— 新进程读同一份表，昨天提过的今天仍被拦')
{
  const 子脚本 = `
const 冷却 = require(${JSON.stringify(模块路径)})
const 门控 = require(${JSON.stringify(门控路径)})
const 策略 = 门控.加载策略({ 路径: ${JSON.stringify(配置路径)}, 静默: true }).策略
const 读 = 冷却.读冷却({ 路径: ${JSON.stringify(路2)}, 静默: true })
const 上下文 = 冷却.取上下文(读.表)
const 结果 = 门控.门控([{ 记忆ID: 'mem-A', 族: 'literal', 交集数: 3, 余弦: 0.99 }], 策略, 上下文)
console.log(JSON.stringify({ 来源: 读.来源, 开口: 结果.开口, 理由: 结果.理由, 上下文键: Object.keys(上下文.已提记录) }))
`
  const r = spawnSync(process.execPath, ['-e', 子脚本], { encoding: 'utf8' })
  let 输出 = null
  try { 输出 = JSON.parse((r.stdout || '').trim().split('\n').filter(Boolean).pop()) } catch (e) {}
  断言('③-1', '新进程能读到落盘表（来源=磁盘而非新建）', 输出 && 输出.来源 === '磁盘', `来源=${输出 && 输出.来源}｜stderr=${(r.stderr || '').slice(0, 200)}`)
  断言('③-2', '新进程里同一条记忆被冷却闸拦下（不为它重复开口）', 输出 && 输出.开口 === false, `开口=${输出 && 输出.开口}｜理由=${输出 && 输出.理由}`)
  断言('③-3', '拦截理由明确写着「冷却中」而非笼统「不准」', !!输出 && /冷却中/.test(输出.理由 || ''), 输出 && 输出.理由)
}

// ═══════════════════════════════════════════
// ④ 删主文件 → 从 .bak 自愈
// ═══════════════════════════════════════════
小标题('④ 断表演练二 —— 主文件被删，从备份自愈，仍不重复提话')
{
  // 先制造一次写，确保 .bak 存在（第二次写会把第一版主文件备份过去）
  冷却.登记提话(造候选('mem-B'), { 路径: 路2, 现在: 基准时 + 1000, 策略, 来源案: 'A', 静默: true })
  const 有备份 = fs.existsSync(路2 + '.bak')
  fs.unlinkSync(路2)
  const 读 = 冷却.读冷却({ 路径: 路2, 静默: true })
  const 上下文 = 冷却.取上下文(读.表)
  const 结果 = 门控策略.门控([造候选('mem-A')], 策略, 上下文)
  断言('④-0', '.bak 备份确实存在（自愈的前提）', 有备份)
  断言('④-1', '主文件丢失后读取不抛错、来源标为「从备份恢复」', 读.来源 === '从备份恢复', `来源=${读.来源}`)
  断言('④-2', '恢复出来的记录里仍有 mem-A', !!上下文.已提记录['mem-A'], JSON.stringify(Object.keys(上下文.已提记录)))
  断言('④-3', '恢复后门控仍拦下这条（没因丢文件而重复提话）', 结果.开口 === false, `开口=${结果.开口}｜理由=${结果.理由}`)
  断言('④-4', '自愈时把干净的表回写成了主文件', fs.existsSync(路2), `存在=${fs.existsSync(路2)}`)
}

