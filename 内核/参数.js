/** 全部参数（当前值 + 元数据 + 是否被改过），供面板渲染 */
function 面板数据() {
  const 原 = 读原始()
  const 组 = {}
  const 参数 = 清单.map(p => {
    const 当前 = p.类型 === '小数' ? 取数(p.键, p.默认) : (p.类型 === '布尔' ? 取布尔(p.键, p.默认) : 取(p.键, p.默认))
    const 改过 = 原.值 && 原.值[p.键] !== undefined && (
      p.类型 === '布尔' ? 取布尔(p.键, p.默认) !== p.默认 : Number(原.值[p.键]) !== p.默认
    )
    const 项 = {
      键: p.键, 名: p.名, 层: p.层, 默认: p.默认, 类型: p.类型 || '整数', 步长: p.步长 || 1,
      最小: p.最小, 最大: p.最大, 可调: p.可调 !== false,
      说明: p.说明, 影响: p.影响, 当前, 已改: !!改过,
      // 档：'通用' = 敢给零基础用户拧的（语义直白、拧错了也只是效果差一点）；缺省 = 专业版才出现
      档: p.档 === '通用' ? '通用' : '专业',
      // 重要：越大越靠上。定于 2026-11-02：“越重要越常用的往上面放”。
      // 0 = 没标（默认排在标过的后面），面板按它降序稳定排。
      重要: Number(p.重要) || 0,
      通俗名: p.通俗名 || '', 通俗说明: p.通俗说明 || ''
    }
    ;(组[p.层] = 组[p.层] || []).push(项)
    return 项
  })
  return {
    ok: true,
    配置文件,
    加载错误: 原.错误,
    文件存在: 原.mtimeMs >= 0,
    组,
    参数
  }
}

/** 写参数：{键: 值}。先整批校验，全过才落盘（原子写 tmp → rename）。 */
function 写(改动) {
  if (!改动 || typeof 改动 !== 'object') return { ok: false, 原因: '改动必须是 {键: 值}' }
  const 已写 = {}
  const 拒绝 = []
  for (const [键, 值] of Object.entries(改动)) {
    const 项 = 索引.get(键)
    if (!项) { 拒绝.push({ 键, 原因: '不认识的参数名（清单见 内核/参数.js）' }); continue }
    if (项.可调 === false) { 拒绝.push({ 键, 原因: '模型固有量，不可调：' + 项.影响.replace(/^⚠\s*不可调。/, '') }); continue }
    if (项.类型 === '布尔') {
      let 布 = null
      if (typeof 值 === 'boolean') 布 = 值
      else if (值 === 'true' || 值 === 1 || 值 === '1') 布 = true
      else if (值 === 'false' || 值 === 0 || 值 === '0') 布 = false
      if (布 === null) { 拒绝.push({ 键, 原因: '只接受 true/false' }); continue }
      已写[键] = 布
      continue
    }
    const 数 = Number(值)
    if (!Number.isFinite(数)) { 拒绝.push({ 键, 原因: '不是数字' }); continue }
    const 落 = 项.类型 === '小数' ? +(数.toFixed(3)) : Math.round(数)
    if (落 < 项.最小 || 落 > 项.最大) { 拒绝.push({ 键, 原因: `超出范围 [${项.最小}, ${项.最大}]` }); continue }
    已写[键] = 落
  }
  if (拒绝.length) return { ok: false, 原因: '有一项不合规，整批未写', 拒绝 }
  if (!Object.keys(已写).length) return { ok: true, 已写: {}, 说明: '没有要改的' }

  try {
    let 文 = {}
    try { 文 = JSON.parse(fs.readFileSync(配置文件, 'utf8')) } catch { 文 = {} }
    if (!文 || typeof 文 !== 'object') 文 = {}
    if (!文.值 || typeof 文.值 !== 'object') 文.值 = {}
    Object.assign(文.值, 已写)
    fs.mkdirSync(path.dirname(配置文件), { recursive: true })
    const 临时 = 配置文件 + '.tmp-' + process.pid
    fs.writeFileSync(临时, JSON.stringify(文, null, 2) + '\n', 'utf8')
    fs.renameSync(临时, 配置文件)
    _缓存 = { mtimeMs: -1, 大小: -1, 值: {}, 读到: 0, 错误: null } // 逼下次重读
    return { ok: true, 已写, 生效: '下一次调用即生效，无需重启' }
  } catch (e) {
    return { ok: false, 原因: '写盘失败：' + String((e && e.message) || e) }
  }
}

