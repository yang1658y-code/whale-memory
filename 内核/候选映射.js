/**
 * 候选映射.js — L4 候选映射层（项目「会记得你的鲸鱼」）
 *
 * 一句话职责：
 *   把「检索结果」翻成「门控判得了的候选集」，并给每条候选挂上原话坐标（句ID）。
 *
 * 【为什么需要这一层】
 *   L5 门控只认 {记忆ID, 族, 交集数, 余弦} 四个字段，而 向量记忆.js 的
 *   搜索相关混合 吐的是 {content, similarity, 检索路, 文件, 行号, rrf分}。
 *   中间这两张皮不接上，L0(提完不忘) + L1(能翻原文) + L5(该不该提) 就各跑各的，
 *   串不成一条线——鲸鱼只能含糊说「我记得这件事」，说不出具体哪一句。
 *
 * 【三件事】
 *   ① 交集数：严格照 门控策略验收.js 的标定口径——两路各自前 N 名有交集 → 3，否则 0。
 *      （44%/95% 那组数就是这么算出来的，改口径等于把标定作废。另出 交集条数 作旁证。）
 *   ② 余弦：取向量路原始相似度（相似度不是得分：搜索相关 的 similarity 未叠时间/权威衰减）。
 *      候选若在向量路无命中 → 余弦记 0（宁可闭嘴，不拿字面分冒充余弦）。
 *   ③ 记忆ID：优先映射成 L1 的句ID（会话A#42.3）→ 一提话就能翻出那句原话；
 *      原文表里找不到 → 用内容哈希 m_xxxx 兜底（冷却照常工作，只是翻不出原话）。
 *
 * 【族怎么判】这一层没有"用户意图"可问，只有检索证据：
 *   该候选被关键词路命中（字面有重叠）→ literal；只在向量路 → rewrite。
 *   宁可把改写族判成字面族之外的一边，也不让活跃档把字面查询当成改写来乱提。
 *
 * 【断依赖】原文表目录不在 / 向量路挂掉 / 两路全空 —— 一律不崩，只少提话。
 *
 * 会记得你的鲸鱼 · 纯中文代码 · 2026-10-27
 */

