const 索引 = new Map()
for (const p of 清单) 索引.set(p.键, p)

// ═══════════════════════ 热读（mtime 变了立刻重读） ═══════════════════════
let _缓存 = { mtimeMs: -1, 大小: -1, 值: {}, 读到: 0, 错误: null }

function 读原始() {
  try {
    const st = fs.statSync(配置文件)
    const 现在 = Date.now()
    // 同一份文件（mtime + 大小未变）在 500ms 内复用，省掉高频调用的系统调用
    if (st.mtimeMs === _缓存.mtimeMs && st.size === _缓存.大小 && 现在 - _缓存.读到 < 500) return _缓存
    const 文 = JSON.parse(fs.readFileSync(配置文件, 'utf8'))
    const 值 = (文 && typeof 文 === 'object' && 文.值 && typeof 文.值 === 'object') ? 文.值 : {}
    _缓存 = { mtimeMs: st.mtimeMs, 大小: st.size, 值, 读到: 现在, 错误: null }
  } catch (e) {
    // 文件不存在 = 正常态（出厂默认就是最佳档），不算错
    _缓存 = {
      mtimeMs: -1, 大小: -1, 值: {}, 读到: Date.now(),
      错误: (e && e.code === 'ENOENT') ? null : String((e && e.message) || e)
    }
  }
  return _缓存
}

/** 取一个参数：值优先 json，其次清单默认，最后调用点兜底。整数会取整并夹进范围。 */
function 取(键, 兜底) {
  const 项 = 索引.get(键)
  const 原 = 读原始()
  const 裸 = 原.值 ? 原.值[键] : undefined
  // 布尔项不取整（Math.round(true) = 1 会把布尔变成数字），走专用分支
  if (项 && 项.类型 === '布尔') return 取布尔(键, 兜底 === undefined ? 项.默认 : 兜底)
  const 数 = (裸 === undefined || 裸 === null || 裸 === '') ? NaN : Number(裸)
  let 值 = Number.isFinite(数) ? 数 : (项 ? 项.默认 : 兜底)
  if (!Number.isFinite(值)) 值 = 兜底
  if (项) {
    值 = Math.round(值)
    if (Number.isFinite(项.最小)) 值 = Math.max(项.最小, 值)
    if (Number.isFinite(项.最大)) 值 = Math.min(项.最大, 值)
  }
  return 值
}

/** 取布尔（'false'/0/'0' 都算 false；读不懂就用默认） */
function 取布尔(键, 兜底) {
  const 项 = 索引.get(键)
  const 原 = 读原始()
  const 裸 = 原.值 ? 原.值[键] : undefined
  const 缺 = (项 && typeof 项.默认 === 'boolean') ? 项.默认 : !!兜底
  if (裸 === undefined || 裸 === null || 裸 === '') return 缺
  if (typeof 裸 === 'boolean') return 裸
  if (裸 === 'true' || 裸 === 1 || 裸 === '1') return true
  if (裸 === 'false' || 裸 === 0 || 裸 === '0') return false
  return 缺
}

/** 取整数（与 取 同源，语义更明确；调用点拿它替换原来的 2024 号常量） */
function 取整(键, 兜底) {
  return Math.round(取(键, 兜底))
}

/** 浮点专用：某些阈值（如补挂 0.7）不能被取整 */
function 取数(键, 兜底) {
  const 项 = 索引.get(键)
  const 原 = 读原始()
  const 裸 = 原.值 ? 原.值[键] : undefined
  const 数 = (裸 === undefined || 裸 === null || 裸 === '') ? NaN : Number(裸)
  let 值 = Number.isFinite(数) ? 数 : (项 ? 项.默认 : 兜底)
  if (!Number.isFinite(值)) 值 = 兜底
  if (项) {
    if (Number.isFinite(项.最小)) 值 = Math.max(项.最小, 值)
    if (Number.isFinite(项.最大)) 值 = Math.min(项.最大, 值)
  }
  return 值
}

