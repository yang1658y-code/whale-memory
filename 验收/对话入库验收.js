// ═══════════════════════ 假向量模块（测试缝） ═══════════════════════
function 造假向量模块(配置 = {}) {
  const 调用 = { 存入: [], 写库: [], 读库: 0, 读档: 0 }
  return {
    调用,
    async 存入消息(...参数) {
      调用.存入.push(参数)
      if (配置.抛错) throw new Error('假模块故意抛错')
      if (配置.返回) return 配置.返回
      return { ok: true, 跳过: false, id: '假_' + 调用.存入.length }
    },
    读取向量库() { 调用.读库++; return 配置.库 || [] },
    async 写入向量库(条目们, 选项) {
      调用.写库.push({ 条数: (条目们 || []).length, 选项 })
      if (配置.写库抛错) throw new Error('假写库故意抛错')
    },
    async 读取归档() { 调用.读档++; return 配置.归档 || [] }
  }
}

