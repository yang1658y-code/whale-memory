// ═══════════════════════ 基础工具 ═══════════════════════

function 正整数(v, 默认值) {
  const n = Number(v)
  return Number.isFinite(n) && n > 0 ? Math.floor(n) : 默认值
}

/**
 * 归一文本：剥 [文件:行号] 前缀 + 去空白 + 去 markdown 噪声
 * 只用于比对，绝不用于展示（展示一律用原文）。
 */
function 归一文本(文本) {
  return String(文本 == null ? '' : 文本)
    .replace(/^\s*\[[^\]]{1,240}\]\s*/, '')
    .replace(/[\s\u3000]+/g, '')
    .replace(/[*`#_~|>]/g, '')
}

/** 双字组（与 原文回溯.js 同口径：去标点空白后取相邻两字） */
function 双字组(文本) {
  const 净 = String(文本 == null ? '' : 文本).toLowerCase().replace(/[\s\p{P}\p{S}]+/gu, '')
  const 组 = new Set()
  if (!净.length) return 组
  if (净.length === 1) { 组.add(净); return 组 }
  for (let i = 0; i < 净.length - 1; i++) 组.add(净.slice(i, i + 2))
  return 组
}

/** 覆盖率：查询的双字组有多少被目标命中（0~1） */
function 覆盖率(查询, 目标) {
  const q = 双字组(查询)
  if (!q.size) return 0
  const t = 双字组(目标)
  let 交 = 0
  for (const g of q) if (t.has(g)) 交++
  return 交 / q.size
}

/** 内容哈希 → 稳定合成记忆ID（同一条记忆多次检索必须同ID，否则冷却表失效） */
function 合成ID(内容) {
  const 净 = 归一文本(内容).slice(0, 240)
  return 'm_' + crypto.createHash('sha1').update(净).digest('hex').slice(0, 12)
}

/**
 * 可提话：这条内容适合从鲸鱼嘴里说出来吗？
 * 表格行、标题行、代码围栏、分隔线、纯链接、极短词——一律不提。
 * 宁可不提，不能在人设上丢人（一句「| 隐私 | 不上报 |」念出来就是程序在说话）。
 *
 * 【2026-10-27 补两条：疑问句 · 空话】
 *   真机复测露的窟窿：用户问「我最近在忙什么」，检索命中的正是这句话自己
 *   （上一轮的同款问句），鲸鱼张嘴就是「你上次说『我最近在忙什么』，我一直记着」
 *   ——复读机，人设当场崩。问句本身不含事实，把问题当记忆还给提问的人，错在最前面。
 *   两条都可关：配置/门控策略.json 的 可提话 段写 false 即回退旧行为。
 */
function 可提话(内容, 选项 = {}) {
  const 原 = String(内容 == null ? '' : 内容).replace(/^\s*\[[^\]]{1,240}\]\s*/, '').trim()
  if (!原) return { 可: false, 原因: '空内容' }
  const 净 = 归一文本(内容)
  if (!净) return { 可: false, 原因: '去掉前缀与符号后为空' }
  if (净.length < 4) return { 可: false, 原因: '归一后不足 4 字：' + 净 }
  if (/^\|/.test(原) || (原.match(/\|/g) || []).length >= 2) return { 可: false, 原因: '表格行' }
  if (/^#{1,6}\s/.test(原)) return { 可: false, 原因: '标题行' }
  if (/^(```|~~~)/.test(原)) return { 可: false, 原因: '代码围栏' }
  if (/^[-*=─═—_]{3,}\s*$/.test(原)) return { 可: false, 原因: '分隔线' }
  if (/^[-*+]\s*$/.test(原)) return { 可: false, 原因: '纯列表符号' }
  if (/^https?:\/\//.test(原)) return { 可: false, 原因: '纯链接' }
  if (选项.排除空话 !== false && 是空话(净)) return { 可: false, 原因: '空话（只有虚词语气词）：' + 净.slice(0, 20) }
  if (选项.排除疑问句 !== false && 是疑问句(原, 净, 选项)) return { 可: false, 原因: '疑问句：' + 净.slice(0, 30) }
  return { 可: true }
}

// ═══════════════════════ 疑问句 / 空话 判定 ═══════════════════════

const 疑问句默认最长 = 30
// 开头就是疑问词："什么情况""怎么办""为什么这样"
const 疑问句头 = /^(什么|啥|怎么|咋|为什么|为啥|哪|谁|多少|几|是不是|要不要|能不能|有没有|是否|如何|几时|何时|干嘛|干啥|可以吗|行不行|对不对)/
// 结尾落在疑问词上："我最近在忙什么""这事怎么办""你去过吗"
const 疑问句尾 = /(什么|啥|怎么|咋|为什么|为啥|哪里|哪儿|哪个|哪位|哪些|谁|多少|几点|几时|何时|干嘛|干啥|吗|呢|么|嘛)\s*$/
// 带数字 / 英文 / 引号书名号 → 视为"带着具体信息"，仍可提（宁可多提一句，少误杀真记忆）
const 带细节 = /[0-9０-９A-Za-z]|[「」『』《》""'']/

/**
 * 是疑问句吗？只判「短问句」。
 *   长句里通常带着具体事实（"那天到底为什么没去，我到现在也没想明白"），
 *   拦了就变成丢记忆——所以只对 疑问最长字数（默认 30 字）以内的句子动手。
 * @param {string} 原 原文（看问号）
 * @param {string} 净 归一文本（看疑问词）
 * @param {object} 选项 { 疑问最长字数, 疑问豁免含数字英文 }
 */
function 是疑问句(原, 净, 选项 = {}) {
  const 上限 = 正整数(选项.疑问最长字数, 疑问句默认最长)
  if (净.length > 上限) return false
  if (选项.疑问豁免含数字英文 !== false && 带细节.test(净)) return false
  if (/[？?]\s*$/.test(原)) return true
  if (疑问句头.test(净)) return true
  if (疑问句尾.test(净)) return true
  return false
}

/** 空话吗？整句只由虚词/语气词/应答词构成（"好的呢""嗯嗯""是的吧"） */
function 是空话(净) {
  if (!净) return true
  return !/[^\s的了呢吧啊么嘛呀哦哈嘿嗯诶好是]/.test(净)
}

function 内容相合(a, b) {
  const 净a = 归一文本(a)
  const 净b = 归一文本(b)
  if (!净a || !净b) return false
  if (净a === 净b) return true
  const 最短 = 取包含匹配最短()
  if (净a.length >= 最短 && 净b.includes(净a)) return true
  if (净b.length >= 最短 && 净a.includes(净b)) return true
  return false
}

/**
 * 是自引吗？——「本轮输入」与「这条候选」几乎就是同一句话。
 *
 * 【2026-11-02 判据收窄】原先直接用 内容相合()（双向 includes），过宽：
 *   用户「引用原话再提问」时查询会把原句整段包住，被当成复读拦下，
 *   可那正是最该把原话怼回去的时候。
 * 现在只认两种：
 *   ① 归一后完全等值 → 自引（库里存着上一轮的同款问句，提了就是复读）
 *   ② 双向覆盖率都 ≥ 阈值（默认 0.9）→ 自引（改了几个字的同款句）
 * 单向包括不再算：引用 ≠ 复读。
 *
 * 实测（2026-11-02）：同款问句 1.000/1.000 拦；⑤ 那题真记忆 0.214/0.115 放行；
 * 引用式提问 0.765/1.000 放行（旧判据会把这条误杀）。
 */
function 是自引(查询, 目标, 选项 = {}) {
  const 净1 = 归一文本(查询)
  const 净2 = 归一文本(目标)
  if (!净1 || !净2) return false
  if (净1 === 净2) return true
  const 阈 = Number.isFinite(Number(选项.相似度)) ? Number(选项.相似度) : 0.9
  const 最短 = 取包含匹配最短()
  if (净1.length < 最短 && 净2.length < 最短) return false
  return 覆盖率(查询, 目标) >= 阈 && 覆盖率(目标, 查询) >= 阈
}

// ═══════════════════════ 原文索引（句ID 桥） ═══════════════════════

const 索引缓存 = new Map()   // 根目录 → { 会话们, 句表, 句数, 坏行数, 指纹, 建时 }

function 文件指纹(p) {
  try { const s = fs.statSync(p); return s.size + ':' + Math.floor(s.mtimeMs) } catch { return 'x' }
}

/**
 * 建原文索引：扫 数据/原文回溯/原文表-*.jsonl，把「句文本归一 → 句ID」铺成一张表
 * 指纹不变则复用缓存；原文表追加后自动重建（追加一次 = 一条记忆，绝不用旧表糊弄）
 */
function 建原文索引(选项 = {}) {
  const 根目录 = String(选项.根目录 || 回溯.默认根目录)
  let 文件们 = []
  try { 文件们 = fs.readdirSync(根目录).filter(f => /^原文表-.+\.jsonl$/.test(f)).sort() } catch { 文件们 = [] }
  const 指纹 = 文件们.map(f => f + '|' + 文件指纹(path.join(根目录, f))).join(';')
  const 旧 = 索引缓存.get(根目录)
  if (旧 && 旧.指纹 === 指纹) return 旧

  const 句表 = []
  const 会话们 = []
  let 坏行数 = 0
  for (const f of 文件们) {
    const 会话 = f.replace(/^原文表-/, '').replace(/\.jsonl$/, '')
    let 表
    try { 表 = 回溯.读原文表(会话, { 根目录 }) } catch { continue }
    if (!表 || !表.存在) continue
    坏行数 += Number(表.坏行数) || 0
    会话们.push({ 会话, 句数: 表.记录.length, 坏行数: Number(表.坏行数) || 0 })
    for (const r of 表.记录) {
      if (!r || !r.文本) continue
      const 净 = 归一文本(r.文本)
      if (!净) continue
      句表.push({
        句ID: r.句ID, 会话: r.会话 || 会话, 轮次: r.轮次, 句序: r.句序,
        角色: r.角色, 时间: r.时间, 文本: r.文本, 净, 长: 净.length
      })
    }
  }
  const 记录 = { 根目录, 会话们, 句表, 句数: 句表.length, 坏行数, 指纹, 建时: Date.now() }
  索引缓存.set(根目录, 记录)
  return 记录
}

function 清缓存() { 索引缓存.clear() }

/**
 * 在一段文本里找它对应的原句
 * 三种命中：精确 / 句在候选中（候选是整条消息、里面含这一句）/ 候选在句中（候选被截断）
 * 多条命中时按「句越长越具体 → 与查询覆盖度越高 → 轮次越早」排
 */
function 找句(文本, 索引, 查询 = '') {
  const 净 = 归一文本(文本)
  if (!净) return { 命中: false, 原因: '文本为空' }
  if (!索引 || !索引.句表 || !索引.句表.length) return { 命中: false, 原因: '原文表里还没有任何句子' }

  for (const s of 索引.句表) {
    if (s.净 === 净) return { 命中: true, 方式: '精确', 句: s, 候选数: 1 }
  }

  const 候选们 = []
  const 最短长 = 取最短句长()
  for (const s of 索引.句表) {
    if (s.长 < 最短长) continue
    if (净.length >= s.长 && 净.includes(s.净)) 候选们.push({ s, 方式: '句在候选中' })
    else if (净.length >= 最短长 && s.净.includes(净)) 候选们.push({ s, 方式: '候选在句中' })
  }
  if (!候选们.length) return { 命中: false, 原因: '原文表里没有这一句' }

  // 多句都能对上的取法（一条消息常含好几句）：
  //   ① 查询整串被这句包含 → 直接胜出（用户复述的就是它）
  //   ② 与查询覆盖度高的 → 胜（提话要提「被问到的那句」，不是「最长的那个」）
  //   ③ 仍打平 → 长的（信息更多）
  //   ④ 再打平 → 早出现的（保持对话自然顺序）
  const 查询净 = 归一文本(查询)
  const 整串命中 = (s) => !!(查询净 && 查询净.length >= 2 && s.净.includes(查询净))
  候选们.sort((a, b) => (整串命中(b.s) - 整串命中(a.s))
    || (覆盖率(查询, b.s.文本) - 覆盖率(查询, a.s.文本))
    || (b.s.长 - a.s.长)
    || (a.s.轮次 - b.s.轮次) || (a.s.句序 - b.s.句序))
  return { 命中: true, 方式: 候选们[0].方式, 句: 候选们[0].s, 候选数: 候选们.length }
}

/**
 * 取句池：向量条目上挂了 句ID们（L2 双写时写入）→ 把这几句单独拎出来当搜索池
 * 好处：① 不必全表扫；② 绝不会配到别处的相似句上（双写同源，这是根治映射率 0% 的那一步）
 */
function 取句池(索引, 句ID们) {
  if (!索引 || !Array.isArray(索引.句表) || !索引.句表.length) return []
  const 要 = Array.isArray(句ID们) ? 句ID们.filter(x => typeof x === 'string' && x) : []
  if (!要.length) return []
  const 集 = new Set(要)
  return 索引.句表.filter(s => 集.has(s.句ID))
}

/**
 * 定位句：先在字段句池里挑（双写同源，最准），池里挑不到再退回全表反查（老条目/内容被截断）
 * @returns 找句 的返回值，额外带 来源 标记（验收与排障用）
 */
function 定位句(文本, 索引, 查询, 字段池, 声明字段 = false) {
  const 池 = Array.isArray(字段池) ? 字段池 : []
  if (池.length) {
    const 内 = 找句(文本, { 句表: 池 }, 查询)
    if (内.命中) { 内.来源 = '字段句池'; return 内 }
  }
  const 全 = 找句(文本, 索引, 查询)
  if (池.length) {
    全.来源 = 全.命中 ? '字段池未中·全表兜底' : '字段池未中·全表也未中'
  } else if (声明字段) {
    // 条目声明了句ID，但原文表里查无此句（原文表被清/句ID失效）→ 与「压根没挂字段」区分开，值得告警
    全.来源 = 全.命中 ? '字段句ID对不上·全表兜底' : '字段句ID对不上·全表也未中'
  } else {
    全.来源 = 全.命中 ? '全表反查' : '全表反查未中'
  }
  return 全
}

// ═══════════════════════ 两路信号 ═══════════════════════

/** 在对方那一路里找同一份内容，找得到算「互证」 */
function 在路里(项文本, 另一路) {
  if (!Array.isArray(另一路)) return false
  for (const x of 另一路) {
    if (!x) continue
    if (内容相合(项文本, x.content)) return true
  }
  return false
}

/**
 * 两路交集：各自前 N 名的共同命中条数
 * 交集数 按标定口径只取 3 / 0（布尔展开），交集条数 是真实条数，供以后更细的门槛用
 */
function 算交集(向量列, 关键词列, 前N = 取前N()) {
  const A = (向量列 || []).slice(0, 前N)
  const B = (关键词列 || []).slice(0, 前N)
  const 命中 = []
  for (const a of A) {
    for (const b of B) {
      if (内容相合(a.content, b.content)) {
        命中.push({ 向量: 归一文本(a.content).slice(0, 60), 关键词: 归一文本(b.content).slice(0, 60) })
        break
      }
    }
  }
  return { 条数: 命中.length, 交集数: 命中.length >= 1 ? 取交集判定值() : 0, 命中, 前N }
}

/** 从向量路取这条候选的原始余弦（similarity，未叠衰减） */
function 取余弦(项, 向量列) {
  const 净 = 归一文本(项 && 项.content)
  if (!净 || !Array.isArray(向量列)) return 0
  let 最好 = 0
  for (const v of 向量列) {
    const 净v = 归一文本(v && v.content)
    if (!净v) continue
    const 最短 = 取包含匹配最短()
  const 合 = (净v === 净) || (净v.length >= 最短 && 净.includes(净v)) || (净.length >= 最短 && 净v.includes(净))
    if (合) {
      const 余 = Number(v.similarity)
      if (Number.isFinite(余) && 余 > 最好) 最好 = 余
    }
  }
  return +最好.toFixed(6)
}

// ═══════════════════════ 主接口：映射候选集 ═══════════════════════

/**
 * 把检索结果映射成门控候选集
 * @param {string} 查询文本
 * @param {object} 选项 {
 *   topK=5, 前N=3, 根目录,
 *   当前来源,          // 传给 搜索相关 做跨对话过滤
 *   向量列, 关键词列, 融合列,  // 注入用（验收/离线）：一旦注入即不跑真检索
 *   真检索=true,       // false 则完全不碰向量库
 *   最短句长
 * }
 * @returns {{查询, 候选集, 诊断}}
 */
async function 映射候选集(查询文本, 选项 = {}) {
  const 开始 = Date.now()
  const 查询 = String(查询文本 == null ? '' : 查询文本)
  const topK = 正整数(选项.topK, 取TopK())
  const 前N = 正整数(选项.前N, 取前N())
  const 来源 = 选项.当前来源 || null

  const 诊断 = {
    版本, 查询: 查询.slice(0, 80), 注入: {},
    向量条数: 0, 关键词条数: 0, 融合条数: 0, 交集条数: 0, 交集数: 0, 前N,
    可回溯数: 0, 原文会话: [], 原文句数: 0, 原文坏行: 0,
    降级: [], 耗时毫秒: 0
  }

  let 向量列 = null
  let 关键词列 = null
  let 融合列 = null
  if (Array.isArray(选项.向量列)) { 向量列 = 选项.向量列; 诊断.注入.向量 = true }
  if (Array.isArray(选项.关键词列)) { 关键词列 = 选项.关键词列; 诊断.注入.关键词 = true }
  if (Array.isArray(选项.融合列)) { 融合列 = 选项.融合列; 诊断.注入.融合 = true }

  const 真检索 = 选项.真检索 !== false && !诊断.注入.向量
  const 向量模块 = 取向量记忆()
  // 【2026-10-27 修】库根目录必须透传给三路检索。
  //   病征：入库走 原文表根（向量库落在同一目录），检索不传根 → 读默认库（包内 数据/ 或 env），
  //   两块盘各写各的 → 永远 0 条候选 → 门控报「候选集为空」→ 鲸鱼永远开不了口。
  //   上游侧注入的 向量记忆.js 多收一个参数会自己忽略，行为不变。
  const 向量根 = 选项.数据根 || 选项.根目录
  const 检索选项 = 向量根 ? { 根目录: 向量根 } : {}

  if (向量列 === null) {
    向量列 = []
    if (真检索 && 向量模块) {
      try { 向量列 = (await 向量模块.搜索相关(查询, topK, 来源, 检索选项)) || [] }
      catch (e) { 诊断.降级.push('向量路异常：' + ((e && e.message) || e)) }
    } else if (真检索 && !向量模块) 诊断.降级.push('向量记忆模块不可用')
  }

  if (关键词列 === null) {
    关键词列 = []
    if (选项.真检索 !== false && 向量模块 && !诊断.注入.关键词) {
      try { 关键词列 = 向量模块.关键词检索(查询, topK, 检索选项) || [] }
      catch { 诊断.降级.push('关键词路异常') }
    }
  }

  if (融合列 === null) {
    if (真检索 && 向量模块) {
      try { 融合列 = (await 向量模块.搜索相关混合(查询, topK, 来源, 检索选项)) || [] }
      catch (e) { 诊断.降级.push('混合检索异常：' + ((e && e.message) || e)); 融合列 = [] }
    } else 融合列 = []
    // 融合列拿不到（或注入两路做离线）→ 自融合：向量在前，关键词补位，保证候选不凭空消失
    if (!融合列.length) {
      const 已收 = new Set()
      const 合 = []
      for (const v of 向量列) {
        const 键 = 归一文本(v && v.content).slice(0, 160)
        if (!键 || 已收.has(键)) continue
        已收.add(键); 合.push(Object.assign({ 检索路: '向量' }, v))
      }
      for (const k of 关键词列) {
        const 键 = 归一文本(k && k.content).slice(0, 160)
        if (!键 || 已收.has(键)) continue
        已收.add(键); 合.push(Object.assign({ 检索路: '关键词' }, k))
      }
      融合列 = 合.slice(0, topK)
    }
  }

  诊断.向量条数 = 向量列.length
  诊断.关键词条数 = 关键词列.length
  诊断.融合条数 = 融合列.length
  if (!向量列.length) 诊断.降级.push('向量路无命中（可能是向量服务未起或库太小）')

  const 交集 = 算交集(向量列, 关键词列, 前N)
  诊断.交集条数 = 交集.条数
  诊断.交集数 = 交集.交集数
  诊断.交集明细 = 交集.命中

  const 索引 = 建原文索引(选项)
  诊断.原文会话 = 索引.会话们.map(s => s.会话 + '(' + s.句数 + '句)')
  诊断.原文句数 = 索引.句数
  诊断.原文坏行 = 索引.坏行数
  if (!索引.句数) 诊断.降级.push('原文表里没有句子 → 候选全部只能翻到检索原文，翻不到轮次/句序')

  // 可提话的开关来自门控策略的 可提话 段（提话链路会把它塞进 选项.策略）；
  // 外部直接调本函数（验收/离线演练）没带策略时按「默认全开」走
  const 可提话选项 = (选项.可提话 && typeof 选项.可提话 === 'object')
    ? 选项.可提话
    : ((选项.策略 && 选项.策略.可提话 && typeof 选项.策略.可提话 === 'object') ? 选项.策略.可提话 : {})

  const 候选集 = []
  诊断.滤掉条数 = 0
  诊断.滤掉明细 = []
  诊断.字段命中数 = 0
  诊断.全表反查数 = 0
  for (const 项 of 融合列) {
    if (!项) continue
    const 适 = 可提话(项.content, 可提话选项)
    if (!适.可) {
      诊断.滤掉条数++
      if (诊断.滤掉明细.length < 5) 诊断.滤掉明细.push(适.原因 + '｜' + 归一文本(项.content).slice(0, 40))
      continue
    }
    // 双写条目挂着 句ID们 → 只在这几句里挑最贴的一句；老条目没挂字段 → 退回全表反查
    const 声明句ID们 = Array.isArray(项.句ID们) && 项.句ID们.length ? 项.句ID们 : (项.句ID ? [项.句ID] : [])
    const 字段池 = 取句池(索引, 声明句ID们)
    const 找 = 定位句(项.content, 索引, 查询, 字段池, 声明句ID们.length > 0)
    const 关键词命中 = 在路里(项.content, 关键词列) || 项.检索路 === '关键词' || 项.检索路 === '双路'
    const 候选 = {
      记忆ID: 找.命中 ? 找.句.句ID : 合成ID(项.content),
      族: 关键词命中 ? 'literal' : 'rewrite',
      交集数: 交集.交集数,
      交集条数: 交集.条数,
      余弦: 取余弦(项, 向量列),
      检索路: 项.检索路 || (关键词命中 ? '关键词' : '向量'),
      可回溯: !!(找.命中),
      rrf分: 项.rrf分 != null ? 项.rrf分 : null,
      内容: String(项.content || '').slice(0, 400)
    }
    if (找.命中) {
      候选.句ID = 找.句.句ID
      if (找.候选数 > 1) 候选.候选句数 = 找.候选数
      候选.会话 = 找.句.会话
      候选.轮次 = 找.句.轮次
      候选.句序 = 找.句.句序
      候选.角色 = 找.句.角色
      候选.时间 = 找.句.时间
      候选.原句 = 找.句.文本
      候选.映射方式 = 找.方式
      候选.映射来源 = 找.来源
      if (找.来源 === '字段句池') 诊断.字段命中数++
      else 诊断.全表反查数++
      诊断.可回溯数++
    } else {
      候选.映射未中原因 = 找.原因
    }
    if (项.文件) 候选.文件 = 项.文件
    if (项.行号 != null) 候选.行号 = 项.行号
    if (Array.isArray(项.命中词)) 候选.命中词 = 项.命中词
    候选集.push(候选)
  }

  诊断.耗时毫秒 = Date.now() - 开始
  return { 查询, 候选集, 诊断 }
}

// ═══════════════════════ 取原话（候选 → 能念出来的一句话） ═══════════════════════

/**
 * 按候选的句ID翻出原话 + 前后各一句（这就是本项目的卖点本体）
 */
function 取原话(候选, 选项 = {}) {
  const 句ID = 候选 && (候选.句ID || (String(候选.记忆ID || '').indexOf('#') > 0 ? 候选.记忆ID : null))
  if (!句ID) {
    return { 找到: false, 原因: '这条候选没有可回溯的句ID（记忆ID=' + (候选 && 候选.记忆ID) + '）', 记忆ID: 候选 && 候选.记忆ID }
  }
  try {
    const r = 回溯.回溯(句ID, {
      前后句数: 选项.前后句数 !== undefined ? 选项.前后句数 : 1,
      跨轮: 选项.跨轮 !== false,
      根目录: 选项.根目录,
      // 话块：一并算出「这句属于谁连着说的哪一段」（同行做法：以对话段为归档单位，不以单条消息为单位）
      段: 选项.段 !== false && Number(选项.前后句数) !== 0
    })
    return r
  } catch (e) {
    return { 找到: false, 原因: '回溯异常：' + ((e && e.message) || e), 句ID }
  }
}

// ═══════════════════════ 端到端：检索 → 映射 → 门控 → 原话 ═══════════════════════

/**
 * 提话链路：一条线串起 L4 + L5
 * @param {string} 查询文本
 * @param {object} 选项 { 上下文, 策略, 当前模型, 登记=true, ...映射选项 }
 * @returns {{开口, 档位, 置信, 措辞, 理由, 命中, 原话, 映射诊断}}
 */
async function 提话链路(查询文本, 选项 = {}) {
  const 诊断 = { 步骤: [] }
  const 门控模块 = 取门控策略()
  if (!门控模块) return { 开口: false, 理由: '门控策略模块不可用', 命中: null, 原话: null, 映射诊断: null }

  let 策略 = 选项.策略
  if (!策略) {
    const 载入 = 门控模块.加载策略({ 当前模型: 选项.当前模型 })
    策略 = 载入.策略
    诊断.策略来源 = 载入.来源 || 载入.路径
    诊断.策略日志 = 载入.日志 || []
    if (载入.降档) 诊断.降档 = true
  }

  // 把归一后的策略带进映射层：可提话（疑问句/空话）的开关就在里面
  const 映射 = await 映射候选集(查询文本, Object.assign({}, 选项, { 策略 }))
  诊断.步骤.push('映射：' + 映射.候选集.length + ' 条候选，可回溯 ' + 映射.诊断.可回溯数 + ' 条')

  const 上下文 = 选项.上下文 || {}
  let 门控结果 = 门控模块.门控(映射.候选集, 策略, 上下文)
  诊断.步骤.push('门控：' + (门控结果.开口 ? '开口' : '闭嘴') + '（' + 门控结果.理由 + '）')

  const 出 = {
    开口: 门控结果.开口, 档位: 门控结果.档位, 置信: 门控结果.置信,
    措辞: 门控结果.措辞, 理由: 门控结果.理由, 命中: null, 原话: null,
    映射诊断: 映射.诊断, 诊断
  }

  // ── 自引闸：本轮输入和命中的原话几乎是同一句 → 提了就是复读 ──
  //   真机案：用户问「我最近在忙什么」，库里存着上一轮的同款问句，
  //   门控一路绿灯，鲸鱼把问句当记忆还回去。这不叫记得，这叫镜像。
  //
  //   【2026-11-02 两处修正】
  //   ① 判据收窄：改用 是自引()（等值 或 双向覆盖率≥0.9），不再用双向 includes。
  //      旧判据会把「引用原话再提问」误杀——而那正是最该把原话怼回去的时候。
  //   ② 拦下 ≠ 整轮闭嘴：把这条候选从池里剔掉，让门控照原口径看下一条。
  //      以前是整链收手，于是「同一句话连问两次」时，第二名真记忆永远提不出来。
  //      全池都被判自引才收手，那时 自引=true 照旧往上报（上层日志分得清）。
  //   拦下时一律不登记冷却（不然白占 30 天名额，真记忆要提时反而提不了）。
  const 可提话配 = (策略 && 策略.可提话 && typeof 策略.可提话 === 'object') ? 策略.可提话 : {}
  const 自引开 = 可提话配.排除自引 !== false
  const 自引阈值 = Number.isFinite(Number(可提话配.自引相似度)) ? Number(可提话配.自引相似度) : undefined
  const 自引收手 = () => Object.assign({}, 出, {
    开口: false,
    措辞: '',
    措辞句: '',
    理由: '自引：命中的原话与本轮输入几乎相同，提了等于复读',
    命中: null,
    原话: null,
    自引: true
  })

  let 池 = Array.isArray(映射.候选集) ? 映射.候选集.slice() : []
  let 本轮原话 = null
  let 自引数 = 0
  while (门控结果.开口 && 门控结果.命中) {
    const 候选 = 门控结果.命中
    const 原话 = 取原话(候选, 选项)
    const 判文本 = (原话 && 原话.找到 && 原话.原句) ? 原话.原句 : (候选.原句 || 候选.内容 || '')
    if (!自引开 || !是自引(查询文本, 判文本, { 相似度: 自引阈值 })) {
      本轮原话 = 原话
      break
    }
    自引数++
    诊断.步骤.push('自引闸：命中「' + 归一文本(判文本).slice(0, 30) + '」与本轮输入几乎相同 → 这条不念，看下一条')
    // 按记忆ID剔（同一对象引用也剔）；没ID的只剔对象本身，不误伤其他候选
    const 剔ID = 候选.记忆ID
    池 = 池.filter(c => c && c !== 候选 && (!剔ID || c.记忆ID !== 剔ID))
    if (!池.length) {
      门控结果 = Object.assign({}, 门控结果, {
        开口: false, 命中: null,
        理由: '全部候选都是自引（' + 自引数 + ' 条）→ 没有可念的记忆'
      })
      break
    }
    门控结果 = 门控模块.门控(池, 策略, 上下文)
    诊断.步骤.push('门控（自引降级后）：' + (门控结果.开口 ? '开口（' + 门控结果.理由 + '）' : '闭嘴（' + 门控结果.理由 + '）'))
  }

  if (!门控结果.开口 || !门控结果.命中) return 自引数 > 0 ? 自引收手() : 出

  const 候选 = 门控结果.命中
  出.开口 = true
  出.档位 = 门控结果.档位
  出.置信 = 门控结果.置信
  出.措辞 = 门控结果.措辞
  出.理由 = 门控结果.理由
  出.命中 = 候选
  出.原话 = 本轮原话 || 取原话(候选, 选项)

  出.措辞句 = 门控模块.渲染措辞(门控结果, 候选.原句 || 候选.内容 || '')
  if (选项.登记 !== false) 门控模块.登记已提(上下文, 候选)
  诊断.步骤.push('原话：' + (出.原话 && 出.原话.找到 ? 出.原话.句ID + '「' + 出.原话.原句 + '」' : '未翻到（记忆ID=' + 候选.记忆ID + '）'))
  return 出
}

