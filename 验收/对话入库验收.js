/**
 * 对话入库验收.js — L2 对话入库双写层（项目「会记得你的鲸鱼」）
 *
 * 跑法：node 验收/对话入库验收.js
 *       node 验收/对话入库验收.js --静默   （只打汇总）
 *
 * 验的不是「代码有没有写」，验的是五件会毁掉产品的事：
 *   ① 次序不许反：先写原文表，再写向量库。原文是唯一事实源。
 *   ② 孤儿条目不许产生：原文表没写成 → 一条向量也不许写。否则鲸鱼会说「我记得」，却翻不出一句原话。
 *   ③ 句ID 必须真挂上：向量条目上的 句ID们 要能在原文表里逐字翻回来（这是「可回溯率」从 0% 变正数的唯一途径）。
 *   ④ 字段优先不许被「长得像」骗：条目挂着句ID时，L4 只能在那几句里挑，绝不因内容相似而配到别处。
 *   ⑤ 断依赖不许崩：向量模块挂了 / 原文目录不可写 / embed 全挂 → 不抛错、只降级，把实情报回来。
 *
 * 会记得你的鲸鱼 · 2026-10-27
 */

