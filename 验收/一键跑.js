#!/usr/bin/env node
/**
 * 会记得你的鲸鱼 · 一键跑全部验收
 * ─────────────────────────────────────────────────────────
 * 跑法：node 验收/一键跑.js
 *       node 验收/一键跑.js --静默     只打最后汇总表
 *
 * 为什么要有它：这套内核的验收不许靠肉眼。改动任何一行内核代码，
 * 一句话跑完十三层断言，退出码 0 才算没砸。
 *
 * 各层：L0 提话冷却持久化 / L1 原文回溯 / L2 对话双写 / L3 向量小模型（随包真语义）
 *      / L4 候选映射 / L5 门控策略 / L5b 疑问句·空话·自引过滤 / L6 QQ适配
 *      / L7 DSH 压缩接管 / L8 DSH 记忆注入 / L9 面板冒烟
 *      / L10 净词体检（仓里不许有内部行话）/ L11 DSH 装机体检（逐字节一致 + 契约点）
 *
 * ═══ 2026-11-02 · 判定为什么变硬了 ═══
 * 改之前，这一层的判定只有一句：`过 = r.status === 0`。
 * 于是「期望」那十个正则定义了整整十次、一次也没参与判定——
 * 某一层从 66 项悄悄掉到 10 项（断言被注释掉一段、或循环提前 return），
 * 只要那 10 项都过，退出码还是 0，一键跑照样绿。README 上 48/48 · 128/128
 * 那张表是人工抄的，机器从来不核。
 *
 * 现在四条硬判，缺一条就红：
 *   ① 退出码必须 0
 *   ② 该层输出必须命中「期望」正则（末行格式没变）
 *   ③ 该层必须打印 `##断言 通过=X 总数=Y`（没报告 = 断言可能整段没了）
 *   ④ 通过 === 总数，且 总数/通过 都不许低于该层「基线」——断言只许增不许减
 * 基线不是装饰：它是「这一层今天真的跑过这么多条」的机器凭据。想减少断言，
 * 必须同时改这里的基线数字，那一步是故意的、看得见的，不会悄悄发生。
 *
 * L3 要跑 650 条语料算 embedding（约 20s），是这套验收里最慢的一层。
 * 它验的是真检索质量（R@5 对撑基线），不可省略——省了它，向量层退化成词袋也没人知道。
 */

const fs = require('fs')
const path = require('path')
const { spawnSync } = require('child_process')
const { 解析: 解析断言 } = require('./断言报告.js')

const 静默 = process.argv.includes('--静默')

// 基线 = 2026-11-02 实测。只许增，不许减（减了必须手改这里，留痕）。
const 清单 = [
  { 层: 'L0', 名: '提话冷却持久化', 文件: '冷却持久化验收.js', 期望: /48\/48/, 基线: { 通过: 48, 总数: 48 } },
  { 层: 'L1', 名: '原文回溯内核', 文件: '原文回溯验收.js', 期望: /通过 \d+ 项/, 基线: { 通过: 128, 总数: 128 } },
  { 层: 'L2', 名: '对话入库双写', 文件: '对话入库验收.js', 期望: /汇总：\d+\/\d+/, 基线: { 通过: 145, 总数: 145 } },
  { 层: 'L3', 名: '向量小模型（随包真语义）', 文件: '向量小模型验收.js', 期望: /向量小模型验收：\d+\/\d+/, 基线: { 通过: 62, 总数: 62 } },
  { 层: 'L4', 名: '候选映射', 文件: '候选映射验收.js', 期望: /汇总：\d+\/\d+/, 基线: { 通过: 108, 总数: 108 } },
  { 层: 'L5', 名: '门控策略', 文件: '门控策略验收.js', 期望: /验收项 \d+ 条/, 基线: { 通过: 20, 总数: 20 } },
  { 层: 'L5b', 名: '疑问句/空话/自引过滤', 文件: '疑问句过滤验收.js', 期望: /过滤验收：通过 \d+\/\d+/, 基线: { 通过: 26, 总数: 26 } },
  { 层: 'L6', 名: 'QQ适配（假事件回放）', 文件: 'QQ适配验收.js', 期望: /QQ适配验收 \d+\/\d+/, 基线: { 通过: 66, 总数: 66 } },
  { 层: 'L7', 名: 'DSH 压缩接管（无模型摘要）', 文件: '压缩接管验收.js', 期望: /压缩接管验收：\d+\/\d+/, 基线: { 通过: 11, 总数: 11 } },
  { 层: 'L8', 名: 'DSH 记忆注入（记得起原话）', 文件: '记忆注入验收.js', 期望: /记忆注入验收：\d+\/\d+/, 基线: { 通过: 18, 总数: 18 } },
  { 层: 'L9', 名: '面板冒烟（真起服务·四接口）', 文件: '面板冒烟验收.js', 期望: /面板冒烟验收（L9）：/, 基线: { 通过: 10, 总数: 10 } },
  { 层: 'L10', 名: '净词体检（仓里不许有内部行话）', 文件: '净词体检.js', 期望: /净词体检（L10）：/, 基线: { 通过: 18, 总数: 18 } },
  { 层: 'L11', 名: 'DSH 装机体检（逐字节一致·契约点）', 文件: 'DSH装机体检.js', 期望: /DSH 装机体检（L11）：/, 基线: { 通过: 16, 总数: 16 } }
]

const 结果 = []
const 开始 = Date.now()

for (const 项 of 清单) {
  const p = path.join(__dirname, 项.文件)
  if (!fs.existsSync(p)) {
    结果.push(Object.assign({}, 项, { 状态: '缺文件', 退出码: -1, 摘要: '', 红: ['文件不存在：' + 项.文件] }))
    continue
  }
  const t0 = Date.now()
  const r = spawnSync(process.execPath, [p, '--静默'], {
    cwd: path.resolve(__dirname, '..'),
    encoding: 'buffer',
    timeout: 300000,
    // 验收必须验「代码」，不能验「用户此刻拧成什么样」。
    // 把参数文件指向一个不存在的路径 → 内核参数模块全走出厂默认（ENOENT 不算错）。
    // 不这么做：谁在面板上把最大字符拧成 1500，L8 断言 900 就莫名其妙变红。
    env: Object.assign({}, process.env, {
      鲸鱼一键跑: '1',
      鲸鱼内核参数: path.join(require('os').tmpdir(), '鲸鱼验收-不出厂的参数文件.json')
    })
  })
  const 文本 = (r.stdout || Buffer.alloc(0)).toString('utf8') + (r.stderr || Buffer.alloc(0)).toString('utf8')
  const 末几行 = 文本.split('\n').map(s => s.trim()).filter(Boolean).slice(-6).join(' ｜ ')

  // ── 四条硬判 ──
  const 红 = []
  if (r.status !== 0) 红.push('退出码 ' + (r.status === null ? '超时' : r.status))
  if (!项.期望.test(文本)) 红.push('末行没命中期望 ' + 项.期望)
  const 断言 = 解析断言(文本)
  if (!断言) {
    红.push('没打印 ##断言（这层没报告，断言可能整段没了）')
  } else {
    if (断言.通过 !== 断言.总数) 红.push('通过 ' + 断言.通过 + '/' + 断言.总数 + '（有失败项）')
    if (断言.总数 < 项.基线.总数) 红.push('断言总数 ' + 断言.总数 + ' < 基线 ' + 项.基线.总数 + '（只许增不许减）')
    if (断言.通过 < 项.基线.通过) 红.push('通过数 ' + 断言.通过 + ' < 基线 ' + 项.基线.通过)
  }
  const 过 = 红.length === 0
  结果.push(Object.assign({}, 项, {
    状态: 过 ? '通过' : '失败',
    退出码: r.status === null ? '超时' : r.status,
    耗时: ((Date.now() - t0) / 1000).toFixed(1) + 's',
    断言: 断言 || null,
    红,
    摘要: 末几行.slice(0, 300)
  }))
  if (!静默) console.log((过 ? '✅' : '❌') + ' ' + 项.层 + ' ' + 项.名 + '（' + ((Date.now() - t0) / 1000).toFixed(1) + 's）' +
    (断言 ? '　断言 ' + 断言.通过 + '/' + 断言.总数 : '') +
    (红.length ? '\n     ✗ ' + 红.join('；') : ''))
}

const 全过 = 结果.every(r => r.状态 === '通过')
const 总耗时 = ((Date.now() - 开始) / 1000).toFixed(1)
const 通过和 = 结果.reduce((s, r) => s + (r.断言 ? r.断言.通过 : 0), 0)
const 总数和 = 结果.reduce((s, r) => s + (r.断言 ? r.断言.总数 : 0), 0)
const 基线和 = 清单.reduce((s, x) => s + x.基线.总数, 0)

console.log('\n' + '═'.repeat(64))
console.log('会记得你的鲸鱼 · 一键验收　' + (全过 ? '全部通过 ✅' : '有失败 ❌'))
console.log('═'.repeat(64))
for (const r of 结果) {
  console.log([r.状态, r.层, r.名, r.耗时 || '-', r.断言 ? r.断言.通过 + '/' + r.断言.总数 : '无报告'].join(' ｜ ').slice(0, 260))
}
for (const r of 结果) if (r.红 && r.红.length) for (const x of r.红) console.log('  ✗ ' + r.层 + ' — ' + x)
console.log('─'.repeat(64))
console.log('断言总计 ' + 通过和 + '/' + 总数和 + '（基线 ' + 基线和 + '，' + (总数和 >= 基线和 ? '未减' : '❗少了 ' + (基线和 - 总数和) + ' 条') + '）')
console.log('总耗时 ' + 总耗时 + 's ｜ 退出码 ' + (全过 ? 0 : 1))

try {
  fs.writeFileSync(path.join(__dirname, '一键跑结果.json'), JSON.stringify({
    时间: new Date().toISOString(), 全过, 总耗时秒: +总耗时,
    断言总计: { 通过: 通过和, 总数: 总数和, 基线: 基线和 },
    明细: 结果.map(r => ({
      层: r.层, 名: r.名, 状态: r.状态, 退出码: r.退出码, 耗时: r.耗时,
      断言: r.断言, 红: r.红, 摘要: r.摘要
    }))
  }, null, 2), 'utf8')
} catch { }

process.exit(全过 ? 0 : 1)
