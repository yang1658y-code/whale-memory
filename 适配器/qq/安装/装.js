#!/usr/bin/env node
'use strict'
/**
 * 装.js · 鲸鱼的 QQ 安装向导（第①步：登录态）
 *
 * 用法：
 *   node 适配器/qq/安装/装.js              开窗口 → 检测登录态 → 没登录就等你扫码 → 登录后往下走
 *   node 适配器/qq/安装/装.js --查登录态    只看不办：报告「已登录/未登录/看不出」然后退出
 *   node 适配器/qq/安装/装.js --无头        无头跑（CI 与验收用；真人装不要用，因为要扫码）
 *   node 适配器/qq/安装/装.js --超时 180    最多等多少秒（默认 300）
 *
 * 为什么第一步是登录态而不是直接抄 AppID：
 *   抄 AppID 要进「开发设置」，而没登录时它给的是登录页。先判定登录态，
 *   已登录的机器上用户一次都不用扫——这是「人只做两步」里能替人省掉的那一步。
 *
 * 零依赖。
 */

const 浏 = require('./浏览器.js')
const 登 = require('./登录态.js')

const 参数 = process.argv.slice(2)
const 有 = (名) => 参数.includes('--' + 名)
const 取值 = (名, 缺省 = null) => { const i = 参数.indexOf('--' + 名); return i >= 0 && 参数[i + 1] ? 参数[i + 1] : 缺省 }

const 只查 = 有('查登录态')
const 无头 = 有('无头')
const 超时秒 = Number(取值('超时', '300')) || 300

function 说(级别, 内容) {
  const 标 = { 步: '▸', 好: '✅', 坏: '❌', 等: '⏳', 注: '·' }[级别] || '·'
  console.log(标 + ' ' + 内容)
}

function 横幅() {
  console.log('')
  console.log('  🐋 会记得你的鲸鱼 · QQ 安装向导')
  console.log('  ────────────────────────────────────────')
  console.log('')
}

async function 主() {
  横幅()

  // ① 找浏览器
  const 找 = 浏.找浏览器()
  if (!找.ok) { 说('坏', 找.说明); return 1 }
  说('好', '用本机已装的 ' + 找.名字 + '：' + 找.路径)

  // ② 起浏览器（独立配置目录，绝不碰用户日常浏览器）
  const 启 = await 浏.启动({ 路径: 找.路径, 无头 })
  if (!启.ok) { 说('坏', 启.说明); return 1 }
  说('好', '浏览器已起（独立配置：' + 启.数据目录 + '）')
  if (!无头) 说('注', '窗口里别关页面；下面需要你动手时我会说')

  let 连 = null
  try {
    // ③ 打开后台入口
    const 开 = await 登.打开后台(启, { 额外等毫秒: 2500 })
    if (!开.ok) { 说('坏', '打开后台失败：' + 开.说明); return 1 }
    连 = 开.连
    const 态 = 开.登录态
    说('注', '落地：' + (态.落地URL || '(读不到)'))
    说(态.已登录 ? '好' : '注', '登录态判定：' + (态.已登录 === true ? '已登录' : 态.已登录 === false ? '未登录' : '看不出') + ' —— ' + 态.判据)

    if (只查) return 态.已登录 === true ? 0 : 2

    if (态.已登录 === true) {
      说('好', '已登录，扫码这一步直接省掉')
    } else {
      console.log('')
      console.log('  ────────── 需要你动手（只有这一步） ──────────')
      console.log('   在弹出的浏览器窗口里：用要挂机器人的那个 QQ 号扫码登录。')
      console.log('   登录完什么都不用点，我这边会自己发现。')
      console.log('  ──────────────────────────────────────────')
      console.log('')
      说('等', '等你登录（最多 ' + 超时秒 + ' 秒）…')
      const 等 = await 登.等登录(连, {
        超时毫秒: 超时秒 * 1000,
        进度回调: (t) => { if (t.已登录 === null) 说('注', '页面状态：' + t.判据) }
      })
      if (!等.已登录) { 说('坏', 等.说明 || '没等到登录'); return 3 }
      说('好', '登录成功（等了 ' + 等.等了秒 + ' 秒）· ' + 等.登录态.判据)
    }

    // ④ 登录态已确认：把落地的后台页留给人看
    const 终 = await 登.检测(连)
    console.log('')
    说('注', '当前页面：' + 终.落地URL)
    if (终.标题) 说('注', '标题：' + 终.标题)
    console.log('')
    说('等', '下一步（未实现）：读机器人列表 → 抄 AppID / AppSecret → 写进 配置/qq.json')
    return 0
  } finally {
    try { if (连) 连.关() } catch { /* 已断 */ }
    await 启.关闭()
  }
}

主().then(码 => process.exit(码)).catch(e => { console.error('❌ 安装向导崩了：', e && e.stack || e); process.exit(1) })
