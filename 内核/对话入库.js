/**
 * 对话入库.js — L2 对话入库双写层（项目「会记得你的鲸鱼」）
 *
 * 一句话职责：
 *   一次调用，把同一轮对话同时写进两处——向量库（能被语义检索到）+ 原文表（能翻出原话），
 *   并让向量条目带上句ID，使 L4 不必靠内容反查也能定位到那句原话。
 *
 * 【为什么非要双写】
 *   L4 候选映射本身是通的，但接真库跑时「可回溯率」是 0%。不是代码错，是两库不同源：
 *     · 向量库存的是整个记忆册（对话记录/文档/记忆册/日志都收）
 *     · 原文表只存「被喂进 L1 的会话」
 *   向量库翻出来的东西，原文表里根本没有 → 鲸鱼只能说「我记得这件事」，说不出哪一句。
 *   本层补的就是这个：入库那一刻就把两处写成同源。
 *
 * 【三条不可违反的次序与红线】
 *   ① 先写原文表，再写向量库。原文是唯一事实源（原文不可丢原则）。
 *   ② 原文表没写成 → 一条向量也不写。宁可少一条记忆，绝不造「翻不出原话的孤儿条目」。
 *   ③ 向量库写挂了不回滚原文：原话在，就是可回溯的；检索路缺了只是少提话，不是丢记忆。
 *
 * 【句ID怎么挂到向量条目上】
 *   一轮对话切成 N 句（句ID = 会话#轮次.句序），而向量库按「消息」存（保留整条语义）。
 *   所以一条消息对应多个句ID → 条目上挂 { 句ID: 首句, 句ID们: 全部, 会话, 轮次 }。
 *   L4 拿到 句ID们 后只在这几条里挑「最贴的一句」：既不会配错到别处，也不用全表扫。
 *
 * 【不做隐式去重】
 *   原文表只追加（这是它的铁律），本层不替调用方判断「这句是不是重复」。
 *   重复由调用方的业务决定；本层只把「跳过」的原因如实报回来。
 *
 * 【断依赖】原文表目录不可写 / 向量模块不可用 / embed 全挂 → 一律不抛错，只在返回值里报。
 *
 * 会记得你的鲸鱼 · 纯中文代码 · 2026-10-27
 */

'use strict'

const 回溯 = require('./原文回溯.js')
const 参数 = require('./参数.js')

const 版本 = 1
const 补挂默认阈值 = 0.7        // 字面分 ≥ 0.7 才认（覆盖率 70%，防把「差不多的句子」当原话）
const 明细上限 = 10
// 两者可调：真值优先取 配置/内核参数.json（热读）
const 取补挂阈值 = () => 参数.取数('对话入库.补挂阈值', 补挂默认阈值)
const 取明细上限 = () => 参数.取整('对话入库.明细上限', 明细上限)

// 懒加载：工具被 require 时不该拖起 embed / 配置文件
// 存储适配器 = 项目对存储层的唯一入口；上游侧由调用方注入 选项.向量模块 换成 向量记忆.js
function 取向量() { try { return require('./存储适配器.js') } catch { return null } }

// ═══════════════════════ 基础工具 ═══════════════════════

/** 取消息正文（与 原文回溯.喂一轮 同口径，否则消息序会跟原文表错位） */
function 取正文(m) {
  if (typeof m === 'string') return m
  if (!m || typeof m !== 'object') return ''
  if (typeof m.文本 === 'string') return m.文本
  if (typeof m.content === 'string') return m.content
  if (typeof m.内容 === 'string') return m.内容
  return ''
}

/** 取消息角色（中英通吃，归一成 用户/助理/系统） */
function 取角色(m) {
  if (!m || typeof m !== 'object') return '用户'
  const 原 = m.角色 || m.role || '用户'
  const 串 = String(原).trim()
  const 低 = 串.toLowerCase()
  if (低 === 'user') return '用户'
  if (低 === 'assistant' || 串 === '助手') return '助理'
  if (低 === 'system') return '系统'
  return 串 || '用户'
}

/** 归一成人/机角色给向量库（它的权威性判定只认 user / assistant / system） */
function 归一向量角色(角色) {
  const 串 = String(角色 == null ? '' : 角色).trim()
  if (串 === '用户') return 'user'
  if (串 === '助理' || 串 === '助手') return 'assistant'   // 「助手」是适配器历史叫法，必须归到 assistant，否则机器人自己的话会被当成用户原话
  if (串 === '系统') return 'system'
  const 低 = 串.toLowerCase()
  if (低 === 'user' || 低 === 'assistant' || 低 === 'system') return 低
  return 'user'
}

/** 正规化消息列表：字符串/单对象/数组都收；正文为空的一律丢（与 喂一轮 的过滤同步） */
function 正规化消息(列表) {
  let 消息 = []
  if (Array.isArray(列表)) 消息 = 列表
  else if (typeof 列表 === 'string') 消息 = [{ 角色: '用户', 文本: 列表 }]
  else if (列表 && typeof 列表 === 'object') 消息 = [列表]
  return 消息.filter(m => 取正文(m).trim() !== '')
}

function 数(v, 默认值) {
  const n = Number(v)
  return Number.isFinite(n) ? n : 默认值
}

// ═══════════════════════ 句ID 分组（按消息序） ═══════════════════════

/**
 * 读完原文表，把这一轮的句ID按「消息序」分好组。
 * 不重复实现切句逻辑——事实源在原文表，读回来分组，永远与落盘的一致。
 * @returns {{组:Map<number,string[]>, 句数:number, 坏行数:number, 存在:boolean}}
 */
function 按消息分组句ID(会话, 轮次, 根目录) {
  const 组 = new Map()
  let 表
  try { 表 = 回溯.读原文表(会话, { 根目录 }) } catch { 表 = null }
  if (!表 || !Array.isArray(表.记录)) return { 组, 句数: 0, 坏行数: 0, 存在: false }
  const 本行 = 表.记录
    .filter(r => Number(r.轮次) === Number(轮次))
    .sort((a, b) => Number(a.句序) - Number(b.句序))
  for (const r of 本行) {
    const 序 = Number(r.消息序) || 1
    if (!组.has(序)) 组.set(序, [])
    组.get(序).push(r.句ID)
  }
  return { 组, 句数: 本行.length, 坏行数: Number(表.坏行数) || 0, 存在: !!表.存在 }
}

// ═══════════════════════ 主接口：入库一轮（双写） ═══════════════════════

/**
 * 入库一轮：原文表 + 向量库，一次写完
 * @param {string} 会话 会话名（原文表按它会话分文件）
 * @param {Array|string|object} 消息列表 [{角色,文本,时间}] / 单条文本 / 单条对象
 * @param {object} 选项 {
 *   轮次?, 时间?, 根目录?,
 *   新鲜度档='稳定', 来源=null, 权威性=null,
 *   写向量=true        // false 则只写原文表（演练/离线用）
 * }
 * @returns {{ok, 会话, 轮次, 原文:{...}, 向量:{...}, 可回溯句数, 降级[], 耗时毫秒, 原因?}}
 */
async function 入库一轮(会话, 消息列表, 选项 = {}) {
  const 选 = Object.assign({ 新鲜度档: '稳定', 来源: null, 权威性: null, 写向量: true }, 选项 || {})
  const 名 = 回溯.归一会话名(会话)
  const 消息们 = 正规化消息(消息列表)
  const 开始 = Date.now()
  const 出 = {
    ok: false, 会话: 名, 轮次: null,
    原文: { 写入: 0, 句ID们: [], 坏行数: 0, 路径: null },
    向量: { 尝试: 0, 写入: 0, 跳过: 0, 失败: 0, 明细: [] },
    可回溯句数: 0, 降级: [], 耗时毫秒: 0
  }

  if (消息们.length === 0) {
    出.原因 = '消息为空或全是空白，双写都没有发生'
    出.耗时毫秒 = Date.now() - 开始
    return 出
  }

  // ① 先写原文表：原文是唯一事实源，先落盘
  let 回溯结果 = null
  try {
    回溯结果 = 回溯.喂一轮(名, 消息们, { 轮次: 选.轮次, 时间: 选.时间, 根目录: 选.根目录 })
  } catch (e) {
    回溯结果 = { 写入: 0, 错误: String((e && e.message) || e) }
  }
  if (!回溯结果 || !回溯结果.写入) {
    出.原因 = '原文表未写成，拒绝写向量库（否则会造出翻不出原话的孤儿条目）：'
      + ((回溯结果 && (回溯结果.错误 || 回溯结果.说明)) || '未知原因')
    出.耗时毫秒 = Date.now() - 开始
    return 出
  }
  出.轮次 = 回溯结果.轮次
  出.原文.写入 = 回溯结果.写入
  出.原文.句ID们 = 回溯结果.句ID们 || []
  出.原文.路径 = 回溯结果.路径 || null
  出.可回溯句数 = 出.原文.写入

  if (选.写向量 === false) {
    出.ok = true
    出.跳过原因 = '调用方指定 写向量=false（只写原文表）'
    出.耗时毫秒 = Date.now() - 开始
    return 出
  }

  // ② 读回这一轮的句ID，按消息序分组
  const 分组 = 按消息分组句ID(名, 出.轮次, 选.根目录)
  出.原文.坏行数 = 分组.坏行数
  if (分组.句数 !== 出.原文.写入) {
    出.降级.push('原文表回读句数（' + 分组.句数 + '）与写入句数（' + 出.原文.写入 + '）不一致，句ID可能挂不全')
  }

  // ③ 写向量库
  //  选项.向量模块 是测试缝：验收注入假模块，生产走真模块（不传即真模块）
  //  注意：显式传 null = 「就是没有向量模块」，绝不能 fallback 回真模块（否则断依赖演练测了个寂寞）
  const 向量 = Object.prototype.hasOwnProperty.call(选, '向量模块') ? 选.向量模块 : 取向量()
  if (!向量 || typeof 向量.存入消息 !== 'function') {
    出.降级.push('向量记忆模块不可用 → 原文表已写，检索路暂缺（记忆仍在，只是暂时提不出来）')
    出.ok = true
    出.耗时毫秒 = Date.now() - 开始
    return 出
  }

  for (let i = 0; i < 消息们.length; i++) {
    const m = 消息们[i]
    const 正文 = 取正文(m)
    const 角色 = 取角色(m)
    const 时间 = 数(m && m.时间, 数(回溯结果.时间, Date.now()))
    const 句ID们 = 分组.组.get(i + 1) || []
    const 附加 = {
      句ID: 句ID们[0] || null,
      句ID们,
      会话: 名,
      轮次: 出.轮次
    }
    出.向量.尝试++
    // 只有调用方显式指定了根目录，才把选项透传给向量层（存储适配器认第9参 选项）
    // 上游侧的 向量记忆.存入消息 只收 8 个参数，多传一个它自己会忽略，行为不变
    // 【根目录 vs 数据根】根目录 = 原文表目录；数据根 = 向量库/冷却所在的数据总根。
  // 生产（DSH）里两者不同：表在 ~/.dsh/whale-memory/原文回溯，向量库在 <包>/数据
  //（junction → ~/.dsh/whale-memory/内核数据）。
  // 只给 根目录 时沿用旧行为（验收靠这一个参数把两边都指到临时目录）。
  const 向量根 = 选.数据根 || 选.根目录
  const 存选项 = 向量根 ? { 根目录: 向量根 } : {}
    let r = null
    try {
      r = await 向量.存入消息(
        归一向量角色(角色), 正文, 时间, null,
        选.新鲜度档, 选.来源, 选.权威性, 附加, 存选项
      )
    } catch (e) {
      r = { ok: false, 原因: String((e && e.message) || e) }
    }
    if (r && r.ok && !r.跳过) 出.向量.写入++
    else if (r && r.ok && r.跳过) 出.向量.跳过++
    else 出.向量.失败++
    if (出.向量.明细.length < 取明细上限()) {
      出.向量.明细.push({
        序: i + 1, 角色,
        结果: r && r.ok ? (r.跳过 ? '跳过' : '写入') : '失败',
        原因: (r && r.原因) || null,
        句ID们,
        编号: (r && r.id) || null,
        片段: String(正文).slice(0, 30)
      })
    }
  }

  if (出.向量.写入 === 0 && 出.向量.失败 > 0) {
    出.降级.push('向量库一条都没写进去 → 本轮只能靠字面路检索')
  }
  出.ok = true
  出.耗时毫秒 = Date.now() - 开始
  return 出
}

/**
 * 入库多轮：[{轮次?, 时间?, 消息列表:[...]}]，逐轮调 入库一轮
 */
async function 入库多轮(会话, 轮列表, 选项 = {}) {
  const 结果 = []
  if (!Array.isArray(轮列表)) return 结果
  for (const 轮 of 轮列表) {
    if (!轮) continue
    const 单轮选项 = Object.assign({}, 选项)
    if (轮.轮次 !== undefined && 轮.轮次 !== null) 单轮选项.轮次 = 轮.轮次
    if (轮.时间 !== undefined && 轮.时间 !== null) 单轮选项.时间 = 轮.时间
    结果.push(await 入库一轮(会话, 轮.消息列表 || 轮.消息 || [], 单轮选项))
  }
  return 结果
}

// ═══════════════════════ 存量补挂（迁移用，默认预览） ═══════════════════════

/**
 * 给库里的老条目补句ID：它们入库时还没有双写，条目上没挂句ID。
 * 用字面分在原文表里找，分够高才挂 —— 宁可不挂，也不乱挂（挂错比不挂坏）。
 * @param {object} 选项 { 执行=false（默认预览不改盘）, 根目录, 最低分=0.7 }
 */
async function 补挂句ID(选项 = {}) {
  const 出 = {
    执行: 选项.执行 === true, 总数: 0, 已有: 0, 待补: 0,
    命中: 0, 未中: 0, 已写回: false, 明细: [], 降级: []
  }
  const 向量 = Object.prototype.hasOwnProperty.call(选项, '向量模块') ? 选项.向量模块 : 取向量()
  if (!向量) { 出.降级.push('向量记忆模块不可用'); return 出 }

  const 阈值 = Number.isFinite(Number(选项.最低分)) ? Number(选项.最低分) : 取补挂阈值()
  let 条目们 = []
  try { 条目们 = 向量.读取向量库() || [] } catch (e) {
    出.降级.push('读向量库失败：' + String((e && e.message) || e))
    return 出
  }
  if (!Array.isArray(条目们)) { 出.降级.push('向量库返回的不是数组'); return 出 }
  出.总数 = 条目们.length

  for (const e of 条目们) {
    if (!e || !e.content) continue
    if (e.句ID || (Array.isArray(e.句ID们) && e.句ID们.length)) { 出.已有++; continue }
    出.待补++
    let top = null
    try {
      const r = 回溯.找原句(e.content, { 根目录: 选项.根目录, topK: 1 })
      top = (r && r.结果 && r.结果[0]) || null
    } catch { top = null }
    if (top && Number(top.分数) >= 阈值) {
      出.命中++
      if (出.明细.length < 取明细上限()) {
        出.明细.push({ 编号: e.id, 句ID: top.句ID, 分数: top.分数, 原句: String(top.文本).slice(0, 40) })
      }
      e.句ID = top.句ID
      e.句ID们 = [top.句ID]
      e.会话 = top.会话
      e.轮次 = top.轮次
    } else {
      出.未中++
      if (出.明细.length < 取明细上限()) {
        出.明细.push({ 编号: e.id, 句ID: null, 分数: top ? top.分数 : 0, 未中原因: '字面分不足 ' + 阈值 })
      }
    }
  }

  if (出.执行 && 出.命中 > 0) {
    try {
      // 防把已归档条目补回热库：归档里的 id 全部列入「不补回」
      let 归档ids = []
      try {
        const 档 = await 向量.读取归档()
        归档ids = (Array.isArray(档) ? 档 : []).map(x => x && x.id).filter(Boolean)
      } catch { 归档ids = [] }
      await 向量.写入向量库(条目们, { 不补回id: 归档ids })
      出.已写回 = true
    } catch (e) {
      出.降级.push('写回失败：' + String((e && e.message) || e))
    }
  } else if (!出.执行) {
    出.提示 = '预览模式：一条都没改盘，确认无误后带 执行:true 再来一次'
  }
  return 出
}

// ═══════════════════════ 健康自检 ═══════════════════════

/**
 * 双写健康度：两库是否同源、多少条目能翻出原话
 * 这是产品能不能「说出那句原话」的体检单，不是给开发看的日志。
 */
function 健康自检(选项 = {}) {
  const 出 = {
    向量条数: 0, 待判: 0, 带句ID条数: 0, 可回溯率: 0,
    原文会话: [], 原文句数: 0, 原文坏行: 0, 降级: [], 结论: ''
  }
  const 向量 = Object.prototype.hasOwnProperty.call(选项, '向量模块') ? 选项.向量模块 : 取向量()
  if (!向量) {
    出.降级.push('向量记忆模块不可用')
  } else {
    let 条目们 = []
    try { 条目们 = 向量.读取向量库() || [] } catch (e) { 出.降级.push('读向量库失败：' + String((e && e.message) || e)) }
    if (Array.isArray(条目们)) {
      出.向量条数 = 条目们.length
      for (const e of 条目们) {
        if (!e) continue
        出.待判++
        if (e.句ID || (Array.isArray(e.句ID们) && e.句ID们.length)) 出.带句ID条数++
      }
    }
  }

  try {
    const 会话们 = 回溯.列会话({ 根目录: 选项.根目录 })
    for (const 名 of 会话们) {
      const 表 = 回溯.读原文表(名, { 根目录: 选项.根目录 })
      出.原文会话.push({ 会话: 名, 句数: (表.记录 || []).length, 坏行数: Number(表.坏行数) || 0 })
      出.原文句数 += (表.记录 || []).length
      出.原文坏行 += Number(表.坏行数) || 0
    }
  } catch (e) {
    出.降级.push('读原文表失败：' + String((e && e.message) || e))
  }

  出.可回溯率 = 出.待判 > 0 ? +(出.带句ID条数 / 出.待判 * 100).toFixed(1) : 0

  if (出.原文句数 === 0) 出.结论 = '原文表是空的 → 所有候选都翻不出原话，先把对话喂进 L2'
  else if (出.向量条数 === 0) 出.结论 = '向量库是空的 → 只能靠字面路检索'
  else if (出.可回溯率 >= 80) 出.结论 = '两库基本同源，鲸鱼说得出原话'
  else if (出.可回溯率 > 0) 出.结论 = '部分同源（' + 出.可回溯率 + '%）→ 跑一次 补挂句ID 可以把存量捞回来'
  else 出.结论 = '两库不同源（0%）→ 新对话走双写后才会涨，存量靠 补挂句ID 迁移'
  return 出
}

