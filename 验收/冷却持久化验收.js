小标题('⑬ 回归 —— 门控策略验收.js 必须仍 20/20')
{
  const 旧脚本 = path.join(__dirname, '门控策略验收.js')
  const r = spawnSync(process.execPath, [旧脚本], { encoding: 'utf8', cwd: 根 })
  const 出 = (r.stdout || '') + (r.stderr || '')
  const 汇总 = 出.match(/验收项\s*(\d+)\s*条：通过\s*(\d+)\s*条，失败\s*(\d+)\s*条/)
  const 总数旧 = 汇总 ? Number(汇总[1]) : -1
  const 通过旧 = 汇总 ? Number(汇总[2]) : -1
  const 失败数 = (出.match(/❌/g) || []).length
  断言('⑬-1', '门控策略验收仍全过（本刀没碰坏 L5）', 总数旧 === 20 && 通过旧 === 20 && 失败数 === 0,
    `旧脚本汇总=${汇总 ? 汇总[0] : '未找到汇总行'}｜❌数=${失败数}｜退出码=${r.status}`)
}

