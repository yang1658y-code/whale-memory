  断言('归一：去掉所有空白与全角空格',
    映射.归一文本(' 这 是\u3000一 句 ') === '这是一句',
    映射.归一文本(' 这 是\u3000一 句 '))

  断言('归一：去掉 markdown 噪声（** ` # | >）',
    映射.归一文本('**臣**记录 `代码` 与 #标题') === '臣记录代码与标题',
    映射.归一文本('**臣**记录 `代码` 与 #标题'))

  const 组 = 映射.双字组('养鲸鱼赛道')
  // 养鲸/鲸鱼/鱼赛/赛道 = 4
  断言('双字组：五字 → 4 个相邻双字组', 组.size === 4, '组数=' + 组.size)

  断言('双字组：去标点（「养鲸鱼，赛道」仍是 4 组）', 映射.双字组('养鲸鱼，赛道').size === 4)

  断言('覆盖率：同文 = 1', 映射.覆盖率('挂份需求单', '先给这个事挂份需求单出来吧。') === 1,
    String(映射.覆盖率('挂份需求单', '先给这个事挂份需求单出来吧。')))

  断言('覆盖率：无关 = 0', 映射.覆盖率('量子计算', '先给这个事挂份需求单出来吧。') === 0,
    String(映射.覆盖率('量子计算', '先给这个事挂份需求单出来吧。')))

  const id1 = 映射.合成ID('需求单已立，且已挂出。')
  const id2 = 映射.合成ID('[记忆/x.md:9] 需求单已立，且已挂出。')
  断言('合成ID：同内容（带不带前缀）→ 同 ID', id1 === id2, id1 + ' / ' + id2)
  断言('合成ID：形如 m_ + 12 位十六进制', /^m_[0-9a-f]{12}$/.test(id1), id1)
  断言('合成ID：不同内容 → 不同 ID', id1 !== 映射.合成ID('完全另一句话。'))

  断言('内容相合：一句在另一句里 → 真相合',
    映射.内容相合('先给这个事挂份需求单出来吧。', '用户：我说的是在DSH养鲸鱼这个赛道上。先给这个事挂份需求单出来吧。'))
