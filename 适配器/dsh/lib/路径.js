/**
 * 会记得你的鲸鱼 · DSH 接管 · 路径层
 *
 * 唯一职责：**算清楚"原文表存在哪"，并且保证归档侧和检索侧算的是同一个目录。**
 *
 * 为什么单独抽一个文件：
 *   以前这活由 归档.js 自己算，而它为了"跟内核一致"去问内核的 默认根目录；
 *   内核的默认根是 `<包目录>/数据/原文回溯`——包目录一升级就被替换，
 *   用户的记忆跟着一起消失。这不是某台机器的问题，是所有用户的定时炸弹。
 *
 * 现在的优先级（从左到右谁先有谁赢）：
 *   ① `鲸鱼原文表`        —— 验收/演练用，指到临时目录，绝不碰真实数据
 *   ② `原文回溯根目录`    —— 内核自己认的键，谁设了它谁说了算（最高兼容）
 *   ③ `鲸鱼数据目录`      —— 老版本遗留键，仍认（其下再拼 原文回溯/）
 *   ④ 用户数据根          —— `~/.dsh/whale-memory/原文回溯`
 *                            ↑ 这是正式落点：跟包目录无关，升级不丢
 *   ⑤ 拿不到 homedir 时   —— 退回 `<包目录>/数据/原文回溯` 兜底（宁可能丢，不许崩）
 *
 * 一致性铁律（改这个文件前必读）：
 *   内核 `原文回溯.js` 的 `默认根目录` 是**模块加载时读一次 env** 得来的常量。
 *   所以本文件导出 `对齐内核根()`：在 require 内核之前把 env 补齐，
 *   内核的默认根就跟我们一致；调用方再显式传 `根目录` 参数，双保险。
 *   只改一边 → 归档到 A、检索查 B → 永远提不到话。
 */

import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const 本目录 = path.dirname(fileURLToPath(import.meta.url))

// 自己写进 env 的值记一份：它不能反过来被当成「用户显式指定」
let 自写根 = ''

/** 插件包根目录（lib 的上一级） */
export const 包根 = path.resolve(本目录, '..')

/** 取环境变量：空白串当没设（Windows 上常见 `set X=` 留空） */
export function 取环境(键) {
  const 值 = process.env[键]
  return typeof 值 === 'string' && 值.trim().length > 0 ? 值.trim() : ''
}

/**
 * 用户级数据根：`~/.dsh/whale-memory`
 * 选它的理由：DSH 自己的 profile 就在 `~/.dsh` 下，同一棵树；
 * 包升级/重装 node_modules 都碰不到它。
 */
export function 用户数据根() {
  let 家 = ''
  try {
    家 = os.homedir()
  } catch {
    家 = ''
  }
  if (家) return path.join(家, '.dsh', 'whale-memory')
  return path.join(包根, '数据') // 极端兜底：拿不到家目录也不能崩
}

/**
 * 解析原文表根目录。
 * @returns {{根:string, 来处:string}} 来处只用于日志和体检，不含用户内容
 */
export function 解析原文表根() {
  const 显式 = 取环境('鲸鱼原文表')
  if (显式) return { 根: path.resolve(显式), 来处: 'env:鲸鱼原文表' }

  const 内核键 = 取环境('原文回溯根目录')
  if (内核键 && path.resolve(内核键) !== 自写根) return { 根: path.resolve(内核键), 来处: 'env:原文回溯根目录' }

  const 旧数据 = 取环境('鲸鱼数据目录')
  if (旧数据) return { 根: path.resolve(旧数据, '原文回溯'), 来处: 'env:鲸鱼数据目录' }

  const 家 = 用户数据根()
  const 根 = path.join(家, '原文回溯')
  return { 根, 来处: 家 === path.join(包根, '数据') ? '包目录兜底' : '用户数据根' }
}

/** 只要路径 */
export function 原文表根() {
  return 解析原文表根().根
}

/**
 * 数据总根：向量库.jsonl / 提话冷却.json 的落点。
 *
 * 和「原文表根」不是一个目录，这是刻意的：
 *   原文表根 = 用户数据根/原文回溯   （句级事实源，按会话分表成百上千个文件）
 *   数据根   = <包>/数据（junction → 用户数据根/内核数据）
 *              （单文件账本：向量库 + 冷却表）
 * 为什么数据根要绕 junction：内核 `存储适配器.默认根目录` 是 require 时定死的常量，
 * 落在包目录里；包一升级就换，用户账本跟着丢。装机器把 `<包>/数据` 做成 junction
 * 接到用户数据根，于是「包内路径」写进去、实际落在包外。
 *
 * ❗改这里前必读：所有往向量层传根目录的地方必须传本函数的值，
 * 不许传 原文表根()——那会让向量库落进原文回溯目录，库分两处，检索各看一边。
 */
export function 数据根() {
  // ⑤ `鲸鱼数据根` —— 验收/演练用：把向量库与冷却表也指到临时目录。
  //   没有这个键，验收里的沙箱只隔离了原文表，向量库还是真实库：
  //   上一轮验收写进去的句子会在下一轮被检索命中 → 同一份验收脚本第一次绿、第二次红。
  //   这不是测试技巧，是可重复性的底线。
  const 显式 = 取环境('鲸鱼数据根')
  if (显式) return path.resolve(显式)
  return path.join(包根, '数据')
}

/**
 * 把解析结果同步给内核。
 *
 * 内核读 env 是在它自己被 require 的那一刻，所以：
 *   - 本函数必须在 `require('<包>/内核/原文回溯.js')` **之前**调用才有效；
 *   - 用户显式设过 `原文回溯根目录` 时一个字节都不动（他的选择优先）。
 * @returns {string} 解析出的根（方便链式调用）
 */
export function 对齐内核根() {
  const { 根 } = 解析原文表根()
  try {
    if (!取环境('原文回溯根目录')) {
      process.env['原文回溯根目录'] = 根
      自写根 = path.resolve(根)
    }
  } catch {
    /* 环境只读或沙箱禁写 → 不影响主流程，调用方仍会显式传 根目录 */
  }
  return 根
}

/** 老数据的常见落点（装机时用来做一次性搬家，只读不删） */
export function 旧数据候选() {
  const 候选 = [path.join(包根, '数据', '原文回溯')]
  const 旧 = 取环境('鲸鱼数据目录')
  if (旧) 候选.push(path.join(path.resolve(旧), '原文回溯'))
  return 候选
}
