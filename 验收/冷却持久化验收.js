// ⑪ 修剪：过期记录与超长流水带
// ═══════════════════════════════════════════
小标题('⑪ 修剪 —— 表不会无限长')
{
  const d = 临时目录('修剪')
  const p = path.join(d, '提话冷却.json')
  const 现在 = 基准时
  const 已提 = {}
  for (let i = 0; i < 100; i++) 已提['旧-' + i] = { 最近: 现在 - 100 * 毫秒每天, 首次: 现在 - 100 * 毫秒每天, 次数: 1 }
  const 流水 = []
  for (let i = 0; i < 600; i++) 流水.push(现在 - i * 1000)
  冷却.存冷却(冷却.归一化表({ 已提记录: 已提, 最近提话: 流水 }, () => {}, 现在), { 路径: p, 现在, 静默: true })
  const 规则 = 冷却.取规则(策略)
  const 表 = 冷却.读冷却({ 路径: p, 静默: true }).表
  const 清掉 = 冷却.修剪表(表, 规则, 现在)
  断言('⑪-1', '100 条 100 天前的旧记录被清掉', 清掉 === 100 && Object.keys(表.已提记录).length === 0,
    `清掉=${清掉}｜剩=${Object.keys(表.已提记录).length}`)
  断言('⑪-2', '流水带被截到上限之内', 表.最近提话.length === 规则.存储.最近提话上限,
    `${表.最近提话.length} / 上限 ${规则.存储.最近提话上限}`)
  断言('⑪-3', '保留的是最近的，不是最早的', 表.最近提话[表.最近提话.length - 1] === 现在,
    `末位=${表.最近提话[表.最近提话.length - 1]}｜现在=${现在}`)
}

