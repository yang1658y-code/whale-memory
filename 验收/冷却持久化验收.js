/**
 * 冷却持久化验收.js — 基线 v9「动工第一刀」的可执行验收
 *
 * 跑法：node 验收/冷却持久化验收.js
 *
 * 验的不是「代码写得对不对」，验的是四件制度上的事：
 *   ① 重启不忘：新进程读同一份落盘表 → 昨天提过的事今天仍被冷却闸拦
 *   ② 坏不断命：主文件坏/丢/全坏 → 不崩、不静默丢证据、能自愈就自愈
 *   ③ 阈值全在外：改配置的 同记忆天，判定跟着变（代码里没有写死的天数）
 *   ④ A/B 共用一张表：开场提过的事，对话中途不许再提
 * 附赠三项：
 *   ⑤ 原子写：不残留 .tmp 半截文件
 *   ⑥ 修剪：过期记录与超长流水带会被清掉（表不会无限长）
 *   ⑦ 回归：门控策略验收.js 那 20 项必须仍 20/20（本刀不许碰坏 L5）
 *
 * 铁律：全部在系统临时目录里跑，绝不碰真实的 数据/提话冷却.json
 */

const fs = require('fs')
const path = require('path')
const os = require('os')
const { spawnSync } = require('child_process')

const 根 = path.resolve(__dirname, '..')
const 模块路径 = path.join(根, '内核', '提话冷却.js')
const 门控路径 = path.join(根, '内核', '门控策略.js')
const 配置路径 = path.join(根, '配置', '门控策略.json')
const 真实落盘 = path.join(根, '记忆', '提话冷却.json')

const 冷却 = require(模块路径)
const 门控策略 = require(门控路径)
const 策略 = 门控策略.加载策略({ 路径: 配置路径, 静默: true }).策略

const 结果清单 = []
function 断言(编号, 名称, 通过, 详情) {
  结果清单.push({ 编号, 名称, 通过: !!通过, 详情 })
  console.log(`${通过 ? '✅' : '❌'} [${编号}] ${名称}${详情 ? '\n     ' + String(详情).replace(/\n/g, '\n     ') : ''}`)
}
function 小标题(t) { console.log('\n' + '═'.repeat(64) + '\n' + t + '\n' + '═'.repeat(64)) }

function 临时目录(名) {
  const d = path.join(os.tmpdir(), '冷却验收_' + 名 + '_' + Date.now() + '_' + Math.floor(Math.random() * 1e4))
  fs.mkdirSync(d, { recursive: true })
  return d
}

const 毫秒每天 = 门控策略.毫秒每天
const 毫秒每小时 = 门控策略.毫秒每小时

// 造一条一定能过 gate 的候选（交集数 ≥ k，族=字面）
function 造候选(记忆ID, 附加) {
  return Object.assign({ 记忆ID, 族: 'literal', 交集数: 3, 余弦: 0.9 }, 附加 || {})
}

// ═══════════════════════════════════════════
// ① 缺文件 → 新建空表，不崩
// ═══════════════════════════════════════════
小标题('① 断表演练 —— 第一次运行（没有任何落盘文件）')
{
  const d = 临时目录('断表')
  const p = path.join(d, '提话冷却.json')
  let 读 = null, 崩 = null
  try { 读 = 冷却.读冷却({ 路径: p, 静默: true }) } catch (e) { 崩 = e }
  断言('①-1', '没有文件时读取不抛错', !崩, 崩 && 崩.message)
  断言('①-2', '返回新建空表（来源可追溯）', 读 && 读.来源 === '新建空表' && Object.keys(读.表.已提记录).length === 0,
    `来源=${读 && 读.来源}｜记录数=${读 && Object.keys(读.表.已提记录).length}`)
  断言('①-3', '空表字段齐全（版本/创建/更新/已提记录/最近提话）',
    读 && 读.表.版本 === 冷却.表版本 && !!读.表.创建 && !!读.表.更新 && !!读.表.已提记录 && Array.isArray(读.表.最近提话),
    JSON.stringify(Object.keys(读 ? 读.表 : {})))
}

