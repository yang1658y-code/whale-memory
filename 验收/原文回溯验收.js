// ═══════════ 验收脚手架 ═══════════
let 通过 = 0
let 失败 = 0
const 失败清单 = []
let 当前组 = ''

// 静默模式：node 验收.js --静默 → 只打汇总和失败项（CI/回归用）
const 静默 = process.argv.includes('--静默')

function 组(名) {
  当前组 = 名
  if (!静默) console.log('\n── ' + 名 + ' ' + '─'.repeat(Math.max(0, 50 - 名.length)))
}

function 断言(名, 条件, 说明) {
  if (条件) {
    通过++
    if (!静默) console.log('  ✅ ' + 名 + (说明 ? '　' + 说明 : ''))
  } else {
    失败++
    失败清单.push('[' + 当前组 + '] ' + 名 + (说明 ? '　' + 说明 : ''))
    console.log('  ❌ ' + 名 + (说明 ? '　' + 说明 : ''))
  }
}

function 相等(名, 实际, 期望) {
  断言(名, JSON.stringify(实际) === JSON.stringify(期望), '实际=' + JSON.stringify(实际) + ' 期望=' + JSON.stringify(期望))
}

// 每个场景一个独立临时根目录
const 临时总根 = fs.mkdtempSync(path.join(os.tmpdir(), '原文回溯验收-'))
let 场景号 = 0
function 新根(名) {
  const p = path.join(临时总根, (++场景号) + '-' + (名 || '场景'))
  fs.mkdirSync(p, { recursive: true })
  return p
}

// ═══════════ 一、切句（无损是唯一要求） ═══════════
组('一、切句：无损 + 偏移精确')

相等('空值不崩', 内核.切句(null).length + 内核.切句(undefined).length + 内核.切句('').length, 0)
相等('数字不崩', 内核.切句(123).length, 1)
相等('两句正常切', 内核.切句('今天天气不错。我们去吃饭吧！').length, 2)
相等('无终止符整段一句', 内核.切句('这句话没有标点结尾').length, 1)

{
  const 样本 = [
    '今天天气不错。我们去吃饭吧！',
    '第一行\n第二行\n\n第四行',
    '他说“好！”然后走了。',
    '真的吗？！我不信……',
    'English sentence one. And two! 中文也来一句。',
    '   \n  \n',
    'AI: v1.5 版本发布了；顺便说下 3.14 这个数。'
  ]
  let 全无损 = true
  let 全偏移 = true
  const 明细 = []
  for (const 文 of 样本) {
    const 段们 = 内核.切句(文)
    const 拼 = 段们.map(d => d.文本).join('')
    if (拼 !== 文) { 全无损 = false; 明细.push('重组不等：' + JSON.stringify(文)) }
    for (const d of 段们) if (文.slice(d.起, d.止) !== d.文本) { 全偏移 = false; 明细.push('偏移错：' + JSON.stringify(d.文本)) }
  }
  断言('七组样本切完重组成分逐字相等', 全无损, 明细.join(' / '))
  断言('每段起/止偏移能原文切回', 全偏移, 明细.join(' / '))
}

{
  const 句 = 内核.切句('他说“好！”然后走了。')
  相等('引号收尾跟随前句（不切成孤零零的引号）', 句.map(d => d.文本), ['他说“好！”', '然后走了。'])
}
{
  const 句 = 内核.切句('真的吗？！我不信……')
  相等('连续终止符合并成一句', 句.map(d => d.文本), ['真的吗？！', '我不信……'])
}
{
  const 句 = 内核.切句('AI: v1.5 版本发布了。')
  相等('英文句点不切（v1.5 不被拆开）', 句.length, 1)
}

